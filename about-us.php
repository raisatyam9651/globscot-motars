</div>
<div class="wpb_text_column wpb_content_element">
<p>Being a permanent magnet motor, magnet characteristics plays a vital role in the performance of motors. Variation in the magnetic properties of magnets used, causes intolerable variations in the specifications of motors. In order to maintain the exact specifications of motors in narrow range, the total flux of magnets used has to be maintained near constant. To ascertain the quality and strength of magnets we have installed a sophisticated equipment to check the critical parameters of magnets such as residual flux density and coercive force. This facility ensures the consistent performance of our motors in the field.</p>
</div> <div class="vc_separator wpb_content_element vc_separator_align_left vc_sep_width_80 vc_sep_pos_align_left vc_sep_color_grey vc_separator-has-text"><span class="vc_sep_holder vc_sep_holder_l"><span class="vc_sep_line"></span></span><h4><b>Electrical Testing</b></h4><span class="vc_sep_holder vc_sep_holder_r"><span class="vc_sep_line"></span></span>
</div>
<div class="wpb_text_column wpb_content_element">
<p>We have a full fledge testing facility at our factory which includes back to back testing facility and eddy current type dynamometer. This enables to check the motor performance under actual load conditions, and verify horse power and efficiency of motor. Each and every motor is tested on the dynamometer, and HP/ efficiency is verified.</p>
</div> <div class="vc_separator wpb_content_element vc_separator_align_left vc_sep_width_80 vc_sep_pos_align_left vc_sep_color_grey vc_separator-has-text"><span class="vc_sep_holder vc_sep_holder_l"><span class="vc_sep_line"></span></span><h4><b>Endurance Testing</b></h4><span class="vc_sep_holder vc_sep_holder_r"><span class="vc_sep_line"></span></span>
</div>
<div class="wpb_text_column wpb_content_element">
<p>Motor is continuously run on endurance testing at the rated load to evaluate the life of bearings and brushes. Further, this simulates the wear and tear of motor parts like brushes, commutator and bearings in the field operations.</p>
</div> <div class="vc_separator wpb_content_element vc_separator_align_left vc_sep_width_80 vc_sep_pos_align_left vc_sep_color_grey vc_separator-has-text"><span class="vc_sep_holder vc_sep_holder_l"><span class="vc_sep_line"></span></span><h4><b>Computer Aided Designs</b></h4><span class="vc_sep_holder vc_sep_holder_r"><span class="vc_sep_line"></span></span>
</div>
<div class="wpb_text_column wpb_content_element">
<p>[TO BE COMPLETED – ANSYS] We are having an exclusive motor design computer program. All major aspects of performance can be analyzed and evaluate prior to the initial stage of product development and testing of motor. This unique systems takes the guess-work out of motor designing. We offer a fast turnaround on preliminary quotations including complete performance data and CAD generated dimensional drawings.</p>
</div> <div class="vc_separator wpb_content_element vc_separator_align_left vc_sep_width_80 vc_sep_pos_align_left vc_sep_color_grey vc_separator-has-text"><span class="vc_sep_holder vc_sep_holder_l"><span class="vc_sep_line"></span></span><h4><b>Ultrasonic Flaw Detector</b></h4><span class="vc_sep_holder vc_sep_holder_r"><span class="vc_sep_line"></span></span>
</div>
<div class="wpb_text_column wpb_content_element">
<p>Magnets used in the motors should be free from internal cracks and porosity, otherwise it leads to the inconsistent performance of motors in the field. These internal cracks may develop in the shipping of magnets and cause motor failures in the fields. We have installed Ultrasonic flaw detectors machine at our plant where each and every magnet is tested. This facility ensures the trouble free performance and long life of our motors.</p>
