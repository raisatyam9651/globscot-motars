<h5><strong>Permanent Magnet DC Motor is Preferable:</strong></h5>
<ul><li>When the Required speeds exceed the linked to the network frequency.</li><li>When a battery or accumulator power supply is required.</li><li>When a high drive torque is required.</li><li>When speed variation is required without resorting to expensive electronics.</li></ul>
<h5><strong>Asynchronous AC Motor is Preferable:</strong></h5>
<ul><li>When fixed speeds determined by the frequency of power supply network can be used (e.g. 2800,1400,950 rpm)</li><li>When higher speed stability is required.</li><li>When an inverter can be fitted for continuous speed change.</li><li>When the motor is exposed to heavy duty,thus reducing maintenance.</li></ul>
