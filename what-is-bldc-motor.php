<p>BLDC stands for Brushless DC motor. BLDC motor is a synchronous motor, which is electronically commutated (no physical commutator is required). The stator consists of three coils which are energized sequentially with the help of a driver card that provides variable voltage using different PWM (Pulse Width Modulation) techniques, based on the feedback received from the rotor position.</p>
<p>Rotor positioning or the speed of the motor can be controlled with or without a sensor. The motor construction of BLDC motor is similar to the PMSM (Permanent Magnet Synchronous Motor). However, both their characteristics differ due to the control techniques and winding layout.</p>
<p>BLDC motor provides wide speed operating range, which is an ideal choice where high reliability, high efficiency &amp; high torque to weight ratio is required. It is capable of providing high torque for wide speed range. Performance-wise BLDC motor is similar to the Brushed DC motor. However, BLDC is more preferable considering that there is no sparking in the armature, due to the absence of brushes, which can wear over a period of time and need replacement.</p>
<h5>FEATURES:</h5>
<ol><li>Low rotor inertia so preferable for high-speed operation</li><li>Highly responsive and quick operation</li><li>High power density</li><li>Highly reliable and energy efficient</li><li>High torque to weight ratio. Compact in size compared to all other motors for a similar power rating</li><li>Less noise</li></ol>
