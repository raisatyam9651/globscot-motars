<p>The engineer who specified the motor is rarely the person who maintains it. Three years later a maintenance manager inherits a fleet of machines and a service interval nobody discussed at purchase. This piece is for that person, and for the engineer who wants the next specification to account for what happens after commissioning.</p>

<h2>What Actually Wears in a Brushed Motor</h2>

<p>Three components consume life in a permanent magnet DC motor, and only one of them is designed to.</p>

<h3>1. The Brushes</h3>
<p>Carbon or copper-graphite brushes are pressed against the rotating commutator by springs. They are a sacrificial component, deliberately softer than the copper they run on, so they wear rather than damaging the commutator. Industrial-grade brushes typically last <strong>3,000 to 5,000 operating hours</strong>, though the figure moves substantially with load, ambient temperature, running speed and how clean the environment is.</p>

<h3>2. The Commutator</h3>
<p>The segmented copper drum the brushes run on. It wears far more slowly than the brushes but not indefinitely. Over successive brush sets it develops grooving, and the mica insulation between segments can stand proud of the worn copper, which then lifts the brushes and causes arcing. At that point the commutator needs skimming and the mica undercutting, which is a workshop operation rather than a field one.</p>

<h3>3. Carbon Dust</h3>
<p>The by-product of normal brush wear is conductive carbon dust. Inside the brush chamber it is expected. Allowed to accumulate across the commutator or into the windings, it creates leakage paths and accelerates everything else. This is why our frames use totally enclosed, fast-replacement or external-column brush housings, so dust stays contained and inspection does not mean stripping the motor. Field procedures are covered in our <a href="/dc-motor-maintenance/">DC motor maintenance guide</a> and in <a href="/blog/dc-motor-maintenance-common-problems-troubleshooting-preventive/">common DC motor problems, troubleshooting and preventive maintenance</a>.</p>

<h2>Why Brushless Eliminates That Failure Mode, and What Replaces It</h2>

<p>A brushless motor has no sliding electrical contact at all. Windings sit on the stationary stator, magnets rotate, and a three-phase inverter does the commutation electronically. Brush wear, commutator wear and carbon dust simply do not exist. Service life becomes bearing-limited, typically <strong>20,000 hours and beyond</strong>.</p>

<p>But nothing is free, and the honest framing is that the failure mode moves rather than vanishes.</p>

<ul>
<li><strong>Bearings become the wear item.</strong> Still the longest-lived component, but now the one that defines overhaul.</li>
<li><strong>The controller becomes a maintenance object.</strong> Electrolytic capacitors age, power semiconductors fail thermally, and a controller in a hot cabinet has its own life expectancy. A brushed motor's "controller" may be a switch.</li>
<li><strong>Diagnosis needs different skills.</strong> Worn brushes are visible and a technician can judge them by eye. A controller fault needs instruments and firmware knowledge. Some maintenance teams are set up for this and some are not.</li>
<li><strong>Repair is often replacement.</strong> A brush set is a consumable. A failed inverter is usually a module swap.</li>
</ul>

<p>Our <a href="/products-bldc-motors/">BLDC motor range</a> and the background piece on <a href="/what-is-bldc-motor/">what a BLDC motor is</a> cover the construction in more detail.</p>

