<p>The decisive variable is almost never the price of a brush set. It is <strong>what a planned stoppage costs you</strong>. On a machine where a service visit means a technician, a ladder and twenty minutes, brushed maintenance is trivial. On a machine embedded in a production line, or mounted at height, or in a sealed cabinet, or in a remote installation, each of those two-to-three stoppages carries a cost that swamps the hardware difference.</p>

<p>Run the arithmetic on your own numbers:</p>

<p><strong>Five-year brushed service cost = (brush sets &times; part cost) + (stoppages &times; labour) + (stoppages &times; downtime cost) + commutator skim</strong></p>

<p>If that total is smaller than the extra upfront cost of a brushless motor plus its controller, brushed wins. If it is larger, it does not. Efficiency differences then sit on top of this, and the operating-cost arithmetic for those is worked through in <a href="/blog/motor-efficiency-ratings-explained-for-equipment-buyers/">motor efficiency ratings explained for equipment buyers</a>.</p>

<h2>Extending Brush Life When Brushed Is the Right Answer</h2>

<ul>
<li><strong>Match brush grade to duty.</strong> Grade selection for load, speed and humidity is a real engineering choice, not a commodity purchase.</li>
<li><strong>Control the ambient.</strong> Heat accelerates wear on both the brushes and the insulation, as covered in <a href="/blog/motor-insulation-classes-explained-class-f-vs-class-h/">motor insulation classes explained</a>.</li>
<li><strong>Avoid chronic overload.</strong> Higher armature current means more heat at the contact face and faster wear.</li>
<li><strong>Keep the chamber clean.</strong> Blow out carbon dust at every inspection rather than only at replacement.</li>
<li><strong>Replace as a set.</strong> Mixing a new brush with a bedded-in one gives uneven current sharing and shortens both.</li>
</ul>

<h2>When Brushed Is Still the Right Economic Choice</h2>

<p>Frequently, and the maintenance argument does not overturn it:</p>

<ul>
<li><strong>Low annual hours.</strong> A barrier or door operator running a few hundred hours a year may never reach a first brush change in the machine's life. See <a href="/blog/dc-motors-for-automatic-doors-and-gates-selection-guide/">DC motors for automatic doors and gates</a>.</li>
<li><strong>Accessible installations.</strong> Where a service visit is cheap, the sacrificial wear item is an advantage, not a liability.</li>
<li><strong>No control electronics in the product.</strong> Adding an inverter to a machine that has none introduces a new failure domain and new compliance work.</li>
<li><strong>Cost-driven high volume.</strong> The controller cost multiplies across every unit shipped.</li>
</ul>

