<p>A point that fails to throw, or throws but does not prove detection, stops trains. When maintainers chase <strong>railway point machine motor problems</strong>, the motor is usually blamed first, yet many point failures start on the track: an obstruction, dry slide chairs, poor packing or a rod out of adjustment. Telling the two apart quickly, and knowing which motor parameters reveal a developing fault, shortens failures and prevents repeats.</p>

<p>This guide is written for signal and telecommunication (S&amp;T) maintainers, signalling contractors and engineers who specify replacement motors. It uses the DC series-wound point machine motors in our <a href="/products-railway-signalling-products/">railway signalling product range</a> as the reference. It sets no acceptance limits: for those, use the machine's RDSO specification, the Indian Railways Signal Engineering Manual and your zonal maintenance schedule.</p>

<div class="alert alert-info gsm-quick-summary" style="background-color: #f0f7fd; border-left: 4px solid #0056b3; padding: 15px; margin: 25px 0;">
<strong>Quick Summary:</strong> Point machine failures fall into two groups. Track and mechanical causes (obstruction, dry slide chairs, packing and gauge defects, rod and clamp-lock adjustment, detection faults) raise the load or defeat locking. Motor and electrical causes (low insulation resistance after water ingress, brush and commutator wear, friction-clutch setting, voltage drop on long cables, induced AC from 25 kV traction, gear wear) reduce what the drive delivers. Trend working current, clutch-slip current, throw time, terminal voltage under load, 500 V insulation resistance and brush length for every point.
</div>

<h2>How a DC Series Point Motor Behaves, and Why Its Current Is So Revealing</h2>

<p>Our point machine motors are DC series-wound machines rated 110 V DC (with a 120 V DC variant), 0.44 kW, 1,700 rpm and 5.3 A maximum, with a 10-minute duty rating and a 20:1 gear ratio (27:1 on the 120 V variant). In a series motor the field winding carries the armature current, so flux rises with current. Below magnetic saturation:</p>

<div class="gsm-equation">\[ T = K\Phi I \approx k\,I^2 \]</div>

<p>This gives the high breakaway torque a point needs, and it makes current a direct gauge of mechanical load: a given load torque draws the same current whatever the supply voltage. Because torque rises roughly with current squared, a 20 % increase in load shows as only about a 10 % rise in current, unlike our <a href="/products-pmdc-motors/">PMDC motors</a>, where torque is simply proportional to current. Treat small, sustained current rises seriously. Speed behaves differently:</p>

<div class="gsm-equation">\[ \omega = \frac{V_t - I\,(R_a + R_f)}{K\Phi(I)} \]</div>

<p>At a fixed load current the flux is fixed, so speed, and therefore throw time, follows the terminal voltage \( V_t \). That gives maintainers two independent signals: <strong>current tells you about the load; throw time at normal current tells you about the supply</strong>. One caution: a series motor speeds up sharply when unloaded, so run any no-load check only where the maintenance instructions permit it, briefly, and compare against the baseline for that motor.</p>

<hr/>

<h2>Track and Mechanical Causes: When the Motor Is Not the Problem</h2>

<ul>
<li><strong>Obstruction:</strong> ballast or debris between tongue and stock rail stops the switch closing; the clutch slips and detection is not proved.</li>
<li><strong>Dry or dirty slide chairs:</strong> friction rises, so working current rises and throw time lengthens, particularly in dust and summer heat.</li>
<li><strong>Packing, gauge and creep:</strong> loose or unpacked sleepers, gauge variation and rail creep make the switch drag or bind at part of the stroke.</li>
<li><strong>Rod and lock adjustment:</strong> detection rods, lock rods, stretcher bars and, on external clamp-lock machines such as our GSM-220, the clamp lock must suit the machine's stroke. Misadjustment causes failure to lock or prove detection even when the motor ran normally.</li>
<li><strong>Detection contacts and circuits:</strong> a point that has thrown fully but shows failed on the panel usually has a contact, wiring or relay fault rather than a drive fault.</li>
</ul>

<p>Track faults increase the load and therefore the working current. Motor faults more often show as low insulation resistance, longer throw time at normal current, or erratic running. For the mechanism itself, see how an <a href="/blog/electric-point-machine-working-importance-railway-signalling/">electric point machine works</a>.</p>

<div style="background: #fff3cd; border: 1px solid #ffeeba; padding: 15px; border-radius: 6px; margin: 20px 0;">
<strong>Field Rule of Thumb:</strong><br/>
All tests on a point in service must be carried out by authorised S&amp;T staff under the disconnection, reconnection and testing procedures of the Signal Engineering Manual and zonal instructions. Never adjust the clutch or detection to make a failing point work; find and correct the cause.
</div>

