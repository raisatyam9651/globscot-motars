<h2>2. Engineering Features of IP67 Railway Motors</h2>

<ul>
<li><strong>Dual-Lip Radial Shaft Seals:</strong> Viton or silicone rotary seals prevent water migration along the rotating output shaft.</li>
<li><strong>Precision Machined Housing with O-Ring Gaskets:</strong> Precision-machined aluminum/iron end-bells sealed with nitrile O-rings eliminate seam leaks.</li>
<li><strong>Vacuum Pressure Impregnation (VPI):</strong> Armature coils undergo double VPI treatment with Class H epoxy varnish, creating a moisture-proof dielectric barrier.</li>
<li><strong>Sealed Cable Gland Terminations:</strong> Heavy-duty IP67 strain-relief cable glands prevent water creeping into terminal boxes.</li>
</ul>

