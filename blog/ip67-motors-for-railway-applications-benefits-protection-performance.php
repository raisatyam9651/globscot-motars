<h2>3. Frequently Asked Questions (FAQs)</h2>

<h3>Q1: What is the difference between IP65 and IP67 motor ratings?</h3>
<p>IP65 motors protect against low-pressure water jets. IP67 motors provide a tighter seal that allows full continuous submersion under 1 meter of water for 30 minutes without leakage.</p>

<h3>Q2: How does Globe Scott Motors test IP67 compliance on railway motors?</h3>
<p>Motors undergo full water immersion testing in pressurized water tanks, followed by high-voltage dielectric insulation testing (1500V AC) to confirm zero moisture ingress.</p>

<h3>Q3: Does IP67 sealing cause internal thermal buildup in the motor?</h3>
<p>Because IP67 motors are totally enclosed non-ventilated (TENV), thermal heat dissipates through heavy aluminum casing conduction. Thermal design uses Class H (180°C) magnet wire to handle high heat.</p>

<h3>Q4: Are IP67 motors approved by RDSO for Indian Railways?</h3>
<p>Yes. RDSO specification IRS S-24 and S-37 mandate IP67 protection for all trackside point machine and signalling motors.</p>

<h3>Q5: Can IP67 motors be used in industrial washdown plants outside railways?</h3>
<p>Yes. IP67 motors are widely used in food processing, chemical plants, wastewater facilities, and marine applications.</p>

<h3>Q6: Do IP67 motor shaft seals wear out over time?</h3>
<p>High-grade Viton shaft seals last between 5 and 10 years depending on rotational RPM and ambient dust levels.</p>

<h3>Q7: What maintenance is required for an IP67 railway motor?</h3>
<p>Routine inspection includes checking external cable gland tightness, inspecting O-ring integrity during brush service, and testing insulation resistance.</p>

