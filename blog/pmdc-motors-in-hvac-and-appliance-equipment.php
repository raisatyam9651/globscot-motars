<p>HVAC and appliance design teams tend to specify motors by habit. A blower needs a motor, the last blower used a certain frame, so the new one gets the same frame at a slightly different rating. It usually works. It also leaves performance and cost on the table, because fan and appliance loads have specific torque behaviour that suits some motor types much better than others.</p>

<p>Here is where a permanent magnet DC motor is genuinely the right call, and where it is not.</p>

<h2>Blower and Fan Applications: Why the Torque Profile Fits</h2>

<p>A fan is a variable-torque load. Torque required rises roughly with the square of speed, and absorbed power roughly with the cube. Two consequences follow that matter for motor choice.</p>

<p>First, <strong>starting torque demand is low</strong>. At standstill the air has no momentum, so a fan is one of the easiest loads to start. A PMDC motor, which produces high torque directly from armature current, has generous margin here even when sized close to its duty point.</p>

<p>Second, <strong>the payoff from speed control is enormous</strong>. Because power follows the cube of speed, running a blower at 80% speed draws roughly half the power. Any cheap route to variable speed is therefore worth a great deal in a fan application.</p>

<p>That is exactly what a permanent magnet DC motor offers. Speed is close to linear with applied armature voltage, so a low-cost PWM chopper gives usable speed control without a three-phase inverter, position sensors or motor-control firmware. The physics behind that linear relationship is set out in our explainer on <a href="/what-is-pmdc-motor/">how a PMDC motor works</a>, and the broader case is in <a href="/benefits-of-using-dc-motors/">the benefits of using DC motors</a>.</p>

<p>Our A60 series at 15&ndash;75 W and A80 series at 45&ndash;200 W cover the majority of small blower and circulation-fan duties, with supply options from 12 V DC to 220 V DC. Frame and dimensional data is on the <a href="/products-pmdc-motors/">PMDC motor range page</a>.</p>

<h2>Appliance Drive Systems: Cost and Controller Simplicity</h2>

<p>Appliance drives look different from fans. They are usually intermittent, often need real starting torque against a static load, and are ruthlessly cost-sensitive because volumes are high.</p>

<p>PMDC motors are the default across this category for good reasons. They run straight from a DC supply with no controller at all where fixed speed is acceptable. Starting torque is high and needs no current-vector control. And an S2 or S3 intermittent duty cycle means total lifetime running hours often stay well inside the brush wear threshold, so the main disadvantage of a brushed machine never materialises.</p>

<p>Typical duties include drive units in mixers and food preparation equipment, portable vacuum and cleaning appliances, powered tools, and the compact drives inside printing and office machines. Where an appliance needs low speed and high torque, a gearhead does the work rather than a bigger motor, and our <a href="/products-pmdc-geared-motors/">PMDC geared motor family</a> with ratios up to 61:1 on the A80 and A92 frames covers most of that range.</p>

<h2>Adjacent Duties in Building and HVAC Equipment</h2>

<ul>
<li><strong>Damper and louvre actuation.</strong> Short travel, high torque, very low duty. A geared PMDC unit with an electromagnetic brake holds position without continuous current.</li>
<li><strong>Condensate and circulation pumps.</strong> Covered in detail in <a href="/blog/pmdc-motors-for-pumps-benefits-applications-selection-guide/">PMDC motors for pumps</a>.</li>
<li><strong>Air curtain and ventilation units.</strong> Fan-law loads again, with the same speed-control economics.</li>
<li><strong>Automatic doors and entrance systems.</strong> Intermittent, high starting torque, cost-driven, as discussed in our <a href="/blog/dc-motors-for-automatic-doors-and-gates-selection-guide/">DC motor guide for automatic doors and gates</a>.</li>
</ul>

<p>The full spread of end markets we supply is on the <a href="/applications/">applications page</a>.</p>

<h2>Where a PMDC Motor Is the Wrong Choice</h2>

<p>This is the part worth reading twice, because HVAC contains the exact conditions that defeat a brushed motor.</p>

<p><strong>High-speed continuous duty.</strong> A commercial ventilation fan running most of the year accumulates thousands of hours annually. Industrial carbon brushes last roughly 3,000 to 5,000 hours. A blower running near-continuously will therefore hit a brush change every year or two, and in a ceiling void or rooftop unit that service visit costs far more than the brushes.</p>

<p><strong>Efficiency-led specifications.</strong> Where the equipment is sold on an efficiency rating, the 78&ndash;88% typical band for a brushed machine against 85&ndash;95% for brushless can decide the specification on its own. The operating-cost arithmetic is worked through in <a href="/blog/motor-efficiency-ratings-explained-for-equipment-buyers/">motor efficiency ratings explained for equipment buyers</a>.</p>

<p><strong>Very high speeds.</strong> Above roughly 10,000 RPM, brush bounce and commutator heating become limiting.</p>

<p>In all three cases the answer is a brushless machine. Our <a href="/products-bldc-motors/">BLDC motor range</a> is built to customer specification, and we developed our own BISON commercial fan around a BLDC drive precisely because continuous fan duty is where brushless pays. The comparison is set out in <a href="/blog/bldc-vs-pmdc-motors-which-is-right-for-your-application/">BLDC versus PMDC motors</a> and, in more depth, in <a href="/blog/pmdc-vs-bldc-motor-application-fit-guide/">the PMDC versus BLDC application fit guide</a>.</p>

<h2>Working With Our Applications Team on a Custom Spec</h2>

<p>For an OEM programme, the useful conversation starts from the fan curve or the load profile rather than a motor part number. Send the required airflow and static pressure, or the load torque and speed at the output, together with supply voltage, duty cycle, ambient temperature and the envelope you have. We model the design in our own motor design program and return performance data with a CAD dimensional drawing, as described in <a href="/blog/importance-of-customization-in-pmdc-motor-design/">the case for customisation in PMDC motor design</a>.</p>

