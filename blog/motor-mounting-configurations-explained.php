<h2>Frequently Asked Questions</h2>

<h3>Q1. What is the difference between B5 flange mount and B14 face mount?</h3>
<p>Both bolt the motor directly to the driven machine through a machined flange with a locating register. A B5 flange is larger with through-holes and carries higher loads. A B14 face is smaller with tapped holes, is more compact, and is rated for lighter duty.</p>

<h3>Q2. When should I use a foot-mounted (B3) motor?</h3>
<p>Choose B3 when the drive is by belt or chain, when the load is heavy or shock-prone, or when you need to shim and realign in service. The base plate carries the load rather than the motor housing, which is the most forgiving arrangement.</p>

<h3>Q3. Which mounting type is best for a gearbox?</h3>
<p>Flange mounting is normal for direct gearbox coupling because the register holds the motor shaft concentric with the gearbox input, removing most alignment error. On an integrated geared motor the gearbox housing becomes the mounting interface.</p>

<h3>Q4. What causes premature bearing failure on a motor?</h3>
<p>Most commonly an overhung load mounted too far from the bearing, an over-tensioned belt, a rigid coupling across a misaligned shaft pair, or soft foot on a foot-mounted machine where the housing is twisted by the hold-down bolts.</p>

<h3>Q5. Does mounting orientation matter?</h3>
<p>Yes. A motor specified for horizontal running and installed shaft-up or shaft-down can see thrust loads and lubrication conditions outside its rating. Always state the intended orientation when specifying.</p>

<h3>Q6. Can Globe Scott Motors supply a custom mounting configuration?</h3>
<p>Yes. B3, B5 and B14 are standard across our PMDC frames, and shaft diameter, length, keyway and flange details can be cut to your drawing. CAD dimensional drawings are supplied with the preliminary quotation.</p>

<h3>Q7. What mounting dimensions should I send with an enquiry?</h3>
<p>Register (spigot) diameter, bolt pitch circle diameter and hole size or thread, shaft diameter and extension length, keyway details, maximum overall length available in your enclosure, and the mounting orientation.</p>

<hr/>

<h2>Conclusion</h2>
<p>Mounting configuration decides who owns shaft alignment, how vibration reaches the bearings, and how much space the drive consumes. Foot mounting gives you adjustability and load capacity, flange and face mounting give you built-in concentricity and a smaller envelope.</p>
<p>Whichever you choose, settle it against a real dimensional drawing before the chassis design is frozen. It is the cheapest correction you will ever make.</p>

