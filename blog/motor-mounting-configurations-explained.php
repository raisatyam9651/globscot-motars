<p>Mounting is the part of motor selection that gets settled last and causes trouble first. The electrical rating is negotiated carefully, then someone picks a mounting because it is what the previous machine used, and eighteen months later a bearing fails early and nobody connects the two events.</p>

<p>This is a short tour of the standard configurations, what each one does to the load path, and the mistakes that cost bearings.</p>

<h2>The Three Standard Geometries</h2>

<h3>B3 &ndash; Foot Mount</h3>
<p>The motor sits on machined feet bolted to a base plate, and the shaft drives through a coupling, belt or chain. Load is carried by the base, not by the motor housing. B3 is the most forgiving arrangement for heavy or shock loads and the easiest to shim, but it consumes the most space and it puts full responsibility for shaft alignment on the installer.</p>

<h3>B5 &ndash; Flange Mount</h3>
<p>A large machined flange with through-holes bolts directly to the driven machine, and the motor hangs from that face. The register spigot locates the shaft concentric with the housing bore, so alignment is largely built in. B5 is compact and repeatable, which is why it dominates gearbox and pump integration. The trade-off is that the flange and its fasteners now carry the motor's weight plus any dynamic load.</p>

<h3>B14 &ndash; Face Mount</h3>
<p>A smaller flange with tapped holes, bolted from the machine side. Mechanically similar to B5 but lighter, more compact and rated for lower loads. B14 suits small drives where space is tight and the motor mass is modest.</p>

<p>Our standard PMDC frames are available in all three. Dimensional tables for the A60, A80, A90 and larger series, including register diameters, pitch circle diameters and shaft data, are published on the <a href="/products-pmdc-motors/">PMDC motor product page</a>, and the geared variants are on the <a href="/products-geared-motors/">geared motor range page</a>.</p>

