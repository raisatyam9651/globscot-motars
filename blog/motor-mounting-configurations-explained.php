<h2>Vibration and Alignment by Mounting Type</h2>

<p>Each geometry fails in a characteristic way.</p>

<p><strong>Foot-mounted motors</strong> suffer from soft foot: one foot does not sit flat, the bolts pull the housing into a twist, and the bearing runs with a preload it was never designed for. Check all feet on the machined base with a feeler gauge before torquing, and shim rather than forcing.</p>

<p><strong>Flange and face mounted motors</strong> transmit driven-machine vibration straight into the motor housing because there is no compliant path between them. Where the driven load is unbalanced, that vibration goes directly through the bearings. A flange mount also makes the motor a cantilever, so any overhung load on the shaft is amplified at the bearing nearest the flange.</p>

<p><strong>All three</strong> are damaged by the same underlying error, which is asking the motor bearing to carry a load it was not sized for.</p>

<h2>Four Mistakes That Cause Premature Bearing Wear</h2>

<ol>
<li><strong>Overhung load from a belt or sprocket too far out on the shaft.</strong> Bearing load rises with the distance from the bearing to the load. Move the pulley as close to the shaft shoulder as the design allows.</li>
<li><strong>Over-tensioned belts.</strong> A tight belt feels safe and is a permanent radial load on the front bearing. Tension to specification, not to feel.</li>
<li><strong>Rigid couplings across a misaligned pair.</strong> A rigid coupling does not absorb misalignment, it transmits it. Use a flexible coupling unless the alignment is genuinely controlled.</li>
<li><strong>Ignoring the mounting orientation.</strong> A motor specified for horizontal running and installed shaft-up can see thrust and lubrication conditions it was never rated for. Tell your supplier the orientation.</li>
</ol>

<p>Bearing and brush wear symptoms and how to read them are covered in our <a href="/dc-motor-maintenance/">DC motor maintenance guide</a> and in more depth in <a href="/blog/dc-motor-maintenance-common-problems-troubleshooting-preventive/">common DC motor problems and preventive maintenance</a>.</p>

<h2>Mounting a Geared Motor or Transaxle</h2>

<p>Once a gearhead is fitted, the gearbox output, not the motor, is what bolts to the machine, and the gearbox has its own radial and axial load limits. Our <a href="/products-pmdc-geared-motors/">PMDC geared motors</a> use parallel-exit steel gears with exit axles up to 20 mm in AISI 303, and the <a href="/products-pmdc-transaxle/">PMDC transaxle range</a> integrates the differential and axles into the drive unit, which changes the mounting problem entirely. Sizing guidance is in <a href="/blog/custom-geared-pmdc-motors-gear-ratio-torque-selection/">selecting gear ratio and torque for custom geared PMDC motors</a> and <a href="/blog/geared-pmdc-motor-working-benefits-applications-selection-guide/">the geared PMDC motor selection guide</a>.</p>

