<h2>3. Frequently Asked Questions (FAQs)</h2>

<h3>Q1: How often should carbon brushes be inspected in industrial DC motors?</h3>
<p>Carbon brushes should be inspected every 1,000 to 2,000 operating hours, or every 3 to 6 months in continuous plant service.</p>

<h3>Q2: What is a healthy commutator patina color?</h3>
<p>A healthy commutator features a uniform dark chocolate brown or copper oxide film. Bright shiny copper indicates severe abrasive brush wear.</p>

<h3>Q3: What causes high mica on a DC motor commutator?</h3>
<p>Because copper segments wear down faster than hard mica insulation strips between them, mica eventually projects above the copper, causing brush bouncing and intense sparking.</p>

<h3>Q4: What insulation resistance reading indicates a safe DC motor winding?</h3>
<p>An insulation resistance reading above 10 MΩ (tested with a 500V DC megger) indicates clean, dry windings. Readings below 1 MΩ require baking and re-varnishing.</p>

<h3>Q5: Can over-lubricating bearings damage a DC motor?</h3>
<p>Yes. Excessive grease gets forced into the motor interior, contaminating carbon brushes and shorting commutator bars.</p>

<h3>Q6: Why do carbon brushes spark more after replacement?</h3>
<p>New brushes must be bedded (curved to match commutator curvature using abrasive bedding stones) before full load operation.</p>

<h3>Q7: When should a brushed DC motor be replaced with a Brushless DC (BLDC) motor?</h3>
<p>Switch to BLDC motors when zero maintenance, high efficiency (> 90%), or hazardous explosive dust protection is required.</p>

