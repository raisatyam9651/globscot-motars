<h2>1. Preventive Maintenance Checklist</h2>

<ul>
<li><strong>Carbon Brush Inspection:</strong> Measure brush length. Replace carbon brushes when worn down to 30% of original height or when spring pressure drops below 2.0 N/cm².</li>
<li><strong>Commutator Surface Care:</strong> Inspect commutator patina (copper oxide film). Clean carbon dust accumulation from commutator mica slots using dry compressed air (< 30 PSI).</li>
<li><strong>Insulation Resistance (Megger Test):</strong> Measure winding insulation resistance to frame using a 500V DC megohmmeter. Insulation resistance should exceed 10 MΩ.</li>
<li><strong>Bearing Lubrication & Vibration Check:</strong> Inspect sealed ball bearings for abnormal noise, elevated temperature (> 85°C), or radial shaft play.</li>
</ul>

