<h2>Frequently Asked Questions</h2>

<h3>Q1. What does it mean that Globe Scott Motors was an Indo-US joint venture?</h3>
<p>The company was established in 1985 with technical collaboration from M/S Scott Motors Inc., USA. That gave the plant a proven permanent magnet DC design methodology from the start, and it was the first company to introduce and manufacture the PMDC motor in India.</p>

<h3>Q2. Why does manufacturing longevity matter when buying motors?</h3>
<p>It matters through three specific mechanisms: mature tooling that produces first articles behaving like series parts, an accumulated failure-mode history that informs brush grade, bearing and sealing choices, and demonstrated supply continuity for products with long service lives.</p>

<h3>Q3. What quality checks does every motor pass through?</h3>
<p>Magnet testing for residual flux density and coercive force, ultrasonic flaw detection on every magnet, armature testing on the machine, dynamometer testing where horsepower and efficiency are verified on every motor, and endurance testing at rated load to evaluate bearing and brush life.</p>

<h3>Q4. Why is magnet testing so important in a PMDC motor?</h3>
<p>In a permanent magnet machine the magnets supply the field, so their properties set the motor's torque and speed constants directly. Variation in magnetic properties produces intolerable variation in motor specifications, which is why total flux is held near constant and every magnet is screened ultrasonically for internal cracks and porosity.</p>

<h3>Q5. What certifications and approvals does Globe Scott Motors hold?</h3>
<p>ISO 9001:2015 certification, CE marking for the low voltage range of motors, NSIC registration, a CRISIL performance and credit rating, and approved supplier status with Indian Railways for point machine motors, point machine systems and electric lifting barriers.</p>

<h3>Q6. Where is the manufacturing facility?</h3>
<p>A1/19, G.I.D.C. Industrial Estate, Killa Pardi 396125, Gujarat, India. Design, tooling, machining, winding, assembly and testing all take place at this single site.</p>

<h3>Q7. Do you export motors from India?</h3>
<p>Yes. Roughly 45% of our DC motors and gearboxes are exported to Europe. Conformity and test certificates are available on request, and we hold CE marking for the low voltage range.</p>

<h3>Q8. How should I compare Indian motor manufacturers?</h3>
<p>Ask whether tooling is owned in-house, whether incoming magnets are inspected, whether every motor is dynamometer tested or only a sample, what independent approvals exist, and how much of the process happens on one site versus through subcontractors.</p>

<hr/>

<h2>Conclusion</h2>
<p>Longevity is a useful proxy for reliability only when you can name the mechanism. For a permanent magnet DC motor plant, the mechanisms are mature tooling, an accumulated failure-mode history, disciplined incoming magnet inspection, dynamometer verification of every unit, and enough independent approval to make supply continuity credible.</p>
<p>Globe Scott Motors has been running all five from the same Killa Pardi plant since 1985. That is what the date on the letterhead is actually worth.</p>

