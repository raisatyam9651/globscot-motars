<h2>1. Working Principle of a Point Machine Motor</h2>
<p>When the signal cabin sends a track switching command, DC electrical power (typically 110V DC or 24V DC) energizes the point machine motor. The high-speed armature rotation is transmitted through an internal gear reduction assembly and friction clutch to drive a rack-and-pinion or throw-bar mechanism.</p>

<ol>
<li><strong>Unlocking Phase:</strong> The motor drives the throw-bar to disengage mechanical locking pins securing the point blades.</li>
<li><strong>Throwing Phase:</strong> High starting torque forces heavy point rails (up to 450 kg throw force) across the stock rails within 3.5 seconds.</li>
<li><strong>Locking Phase:</strong> Mechanical detection locks the switch in the new position, and internal limit switches cut motor current.</li>
</ol>

