<ul>
<li><strong>Automatic doors and gates.</strong> Intermittent, high starting torque, cost sensitive. Almost always PMDC. See our <a href="/blog/dc-motors-for-automatic-doors-and-gates-selection-guide/">DC motor selection guide for automatic doors and gates</a>.</li>
<li><strong>Floor scrubbers and sweepers.</strong> Traction duty with an integrated gearbox, usually a <a href="/products-pmdc-transaxle/">PMDC transaxle</a>, as covered in our article on <a href="/blog/motors-for-industrial-cleaning-machines-pmdc-transaxle-applications/">motors for industrial cleaning machines</a>.</li>
<li><strong>Solar and circulation pumps.</strong> Long continuous run hours favour brushless. Background in <a href="/blog/pmdc-motors-for-pumps-benefits-applications-selection-guide/">PMDC motors for pumps</a>.</li>
<li><strong>Railway carriage fans.</strong> Continuous duty in a sealed enclosure, brushless. Related reading on <a href="/blog/railway-signalling-motors-types-applications-safety-requirements/">railway signalling motors and their safety requirements</a>.</li>
</ul>

<h2>A Two-Question Shortcut</h2>

<p>If you want the decision compressed: <em>how many hours per year does the motor actually turn, and does your product already contain a microcontroller?</em> High hours plus existing control electronics points to BLDC. Low hours plus a simple DC supply points to PMDC. Everything else is refinement, and our deeper comparison of <a href="/blog/pmdc-vs-bldc-motor-application-fit-guide/">PMDC versus BLDC application fit</a> works through the torque-curve and duty-cycle detail. For the long-run cost side, see <a href="/blog/brushed-vs-brushless-motor-maintenance-comparison/">the brushed versus brushless maintenance comparison</a>.</p>

