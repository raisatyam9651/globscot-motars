<h2>3. Frequently Asked Questions (FAQs)</h2>

<h3>Q1: What does RDSO approval mean for railway motors in India?</h3>
<p>RDSO approval certifies that a manufacturer's motor design, factory quality systems, and testing facilities strictly comply with Indian Railways safety and performance specifications.</p>

<h3>Q2: Can non-RDSO approved motors be used on Indian Railways projects?</h3>
<p>No. Deploying non-RDSO approved motors on mainline tracks or signalling infrastructure violates Indian Railways procurement rules and safety regulations.</p>

<h3>Q3: What is the typical lifespan of an RDSO-approved point machine motor?</h3>
<p>RDSO-approved motors are designed for a service life exceeding 10 years or over 500,000 switch throwing operations.</p>

<h3>Q4: Are Globe Scott Motors' railway products RDSO approved?</h3>
<p>Yes. Globe Scott Motors manufactures RDSO-compliant point machine motors, barrier motors, and signalling actuators backed by decades of proven field service.</p>

<h3>Q5: What IP rating is required under RDSO trackside specs?</h3>
<p>RDSO mandates an IP67 rating for all trackside signalling motors to protect against monsoon flooding and ballast dust.</p>

<h3>Q6: What voltage ratings are covered under RDSO railway motor standards?</h3>
<p>Standard approved ratings include 110V DC, 24V DC, 110V AC, and 400V 3-phase AC.</p>

<h3>Q7: How often are RDSO vendor approvals renewed?</h3>
<p>RDSO conducts periodic factory audits and sample testing every 3 to 5 years to maintain vendor registration status.</p>

