<h2>6. Frequently Asked Questions (FAQs)</h2>

<h3>Q1: What is the main advantage of a geared PMDC motor over a direct-drive PMDC motor?</h3>
<p>A geared PMDC motor multiplies torque output proportionally to its gear ratio while reducing output speed, allowing a small, efficient motor to drive heavy mechanical loads that would stall a direct-drive motor.</p>

<h3>Q2: Can a geared PMDC motor be back-driven by the load?</h3>
<p>Spur and planetary geared PMDC motors can be back-driven easily. However, high-ratio worm geared PMDC motors (ratios > 30:1) are inherently self-locking and resist back-driving, keeping loads stationary when unpowered.</p>

<h3>Q3: How does gearbox efficiency affect battery consumption?</h3>
<p>Planetary gearheads (85%–95% efficiency) draw less battery current to produce a given output torque than lower-efficiency worm gearheads (50%–70% efficiency), making planetary geared PMDC motors preferable for mobile battery systems.</p>

<h3>Q4: How long do gearheads last on a PMDC motor?</h3>
<p>With synthetic grease lubrication and operating within rated torque limits, industrial planetary and spur gearboxes typically match or exceed the brush lifetime of the motor (5,000+ operating hours).</p>

<h3>Q5: Can I reverse the rotation of a geared PMDC motor?</h3>
<p>Yes. Reversing the DC supply voltage polarity at the motor terminals reverses the motor direction, which instantly reverses output gear rotation.</p>

<h3>Q6: What causes noise in a geared PMDC motor?</h3>
<p>Noise is primarily generated by gear teeth mesh impacts, high backlash, or insufficient lubrication. Helical and planetary gearheads operate significantly quieter than spur gearheads.</p>

<h3>Q7: What lubrication is used inside PMDC gearboxes?</h3>
<p>Fractional horsepower PMDC gearheads use lifetime synthetic grease (Class NLGI 2), eliminating the need for periodic oil changes.</p>

