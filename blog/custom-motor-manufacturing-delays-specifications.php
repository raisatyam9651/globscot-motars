<p>The calendar time of the whole project can be written as a simple sum:</p>

<div class="gsm-equation">\[ T_{project} = T_{spec} + T_{design} + T_{sample} + T_{val} + n_{loop}\,T_{loop} + T_{appr} + T_{prod} \]</div>

<p>Here \( n_{loop} \) is the number of late changes that force a return to the design stage, and each loop costs roughly \( T_{loop} \approx T_{redesign} + T_{sample} + T_{val} \). Because a loop repeats the slowest engineering stages, one late change can roughly double the sample-to-approval phase, and two can triple it. Manufacturing lead time itself is covered in our article on <a href="/blog/motor-manufacturing-lead-times-explained/">what drives motor manufacturing lead times</a>. The rest of this guide is about keeping \( n_{loop} \) at zero.</p>

