<h2>Seven Root Causes of Custom Motor Manufacturing Delays</h2>

<h3>1. Incomplete Load and Duty-Cycle Data</h3>

<p>A motor frame is sized thermally by its RMS torque over the working cycle, while peak torque sets the magnet design, current limit and gearbox rating. An enquiry that says only "150 W, intermittent" forces the designer to guess both. For a cycle made of segments of torque \( T_k \) lasting \( t_k \):</p>

<div class="gsm-equation">\[ T_{rms} = \sqrt{\frac{\sum T_k^2 \, t_k}{\sum t_k}} \]</div>

<h4>Worked Example: A Duty Cycle That Changed After Samples</h4>

<p>An OEM specifies a geared PMDC drive needing 0.50 Nm at the motor shaft for 15 s, followed by 45 s at rest. Treating the rest period as fully effective cooling for simplicity:</p>

<div class="gsm-equation">\[ T_{rms,1} = 0.50 \times \sqrt{\frac{15}{60}} = 0.25\,\mathrm{Nm} \]</div>

<p>Samples are built and pass their temperature-rise test with margin. During machine trials the cycle is revised to 40 s running and 20 s at rest, giving \( T_{rms,2} = 0.50 \times \sqrt{40/60} \approx 0.41\,\mathrm{Nm} \). Copper loss scales with the square of current, and current with torque, so heating rises by about \( (0.41/0.25)^2 \approx 2.7 \) times. A frame chosen with a comfortable margin at 0.25 Nm RMS will now exceed its thermal limit. The cure, a longer stack or the next frame size, means new samples and a fresh round of validation. Had the real cycle been known, the right frame would have been sampled first time. Our <a href="/blog/motor-torque-and-speed-calculation-practical-guide-industrial-applications/">practical guide to motor torque and speed calculation</a> shows how to build the cycle from the machine's motion profile.</p>

<h3>2. Supply Voltage Specified as a Single Nominal Number</h3>

<p>A PMDC motor's speed follows its terminal voltage almost linearly:</p>

<div class="gsm-equation">\[ N = \frac{60}{2\pi} \cdot \frac{V - I_a R_a - V_{brush}}{K_e} \]</div>

<p>Consider a 24 V motor with \( K_e = 0.075\,\mathrm{V\cdot s/rad} \), \( R_a = 0.40\,\Omega \), a brush drop of about 1.0 V and 6.0 A at the working load, so \( I_a R_a = 2.4\,\mathrm{V} \). On the factory's regulated 24 V bench supply it runs at \( 9.549 \times 20.6/0.075 \approx 2620\,\mathrm{rpm} \). Installed on a lead-acid battery pack that sags to 21 V under load, the same motor runs at \( 9.549 \times 17.6/0.075 \approx 2240\,\mathrm{rpm} \), about 15 % slow; on charge at 28.8 V it runs near 3,230 rpm. The sample passed at the factory but failed in the field; the fix is a new winding and new samples. Our article on <a href="/blog/wrong-motor-voltage-problems-solutions/">wrong motor voltage problems</a> covers the wider consequences.</p>

<div style="background: #fff3cd; border: 1px solid #ffeeba; padding: 15px; border-radius: 6px; margin: 20px 0;">
<strong>Field Rule of Thumb:</strong><br/>
State supply voltage as three numbers measured at the motor terminals under load: minimum, nominal and maximum. For battery systems include low state of charge and charging voltage; for rectified mains include the grid variation actually seen on site.
</div>

<h3>3. Mounting, Shaft and Envelope Changes After Samples</h3>

<p>Mechanical changes vary enormously in effort. A longer shaft extension, a new flat or a different keyway is a machining change. A different flange pitch-circle diameter or spigot may need a new end shield or an adaptor plate. A larger body diameter can mean new laminations or a new housing, which brings tooling time into the schedule; a longer stack normally reuses the laminations but still changes the magnets, housing and armature. Switching between <a href="/blog/motor-mounting-configurations-explained/">B3 foot, B5 flange and B14 face mounting</a> after samples usually falls in the middle group.</p>

<p>The safeguard is to send a dimensioned 2D drawing or STEP model of the mating interface, with tolerances and any overhung load from pulleys or sprockets, before design starts. Where standard sizes genuinely do not fit, our guide on <a href="/blog/custom-motor-design-non-standard-sizes/">custom motor design for non-standard sizes</a> explains which modifications carry low and high effort.</p>

<h3>4. Late Connector, Harness and Lead-Exit Definition</h3>

<p>Leads and connectors look like details, yet often cause a second sample build. Lead exit position and length, wire size, sleeving, connector family and mating half, encoder and brake wiring, and any EMI suppression filter all appear on the motor drawing. Many connectors are bought-out parts with their own supply calendars, and moving a cable gland or exit can alter the sealing, which means repeating ingress tests on a sealed build. Define the harness interface with the same rigour as the shaft.</p>

<h3>5. Undefined Acceptance Tests</h3>

<p>If buyer and manufacturer have not agreed how a sample will be judged, validation cannot finish. "Rated speed 2,800 rpm ±5 %" is incomplete without the test voltage, load point, winding temperature and instrument. Temperature alone moves the numbers, because armature resistance follows:</p>

<div class="gsm-equation">\[ R_T = R_{20}\left[1 + 0.00393\,(T - 20)\right] \]</div>

<p>Between a cold reading at 20 °C and a hot reading at 95 °C, resistance rises by \( 0.00393 \times 75 \approx 0.295 \), almost 30 %, while ferrite magnet flux falls reversibly by roughly 0.2 % per °C of magnet temperature. Hot readings in the customer's machine can therefore differ by several percent from cold readings on the factory dynamometer, with nothing wrong with either. Write the method down before samples are built. The series-supply side, including golden samples, is covered in our article on <a href="/blog/custom-dc-motor-sourcing-oem-mistakes/">custom DC motor sourcing mistakes</a>, and the factory test sequence in <a href="/blog/electric-motor-testing-standards-before-a-unit-ships/">motor testing standards before a unit ships</a>.</p>

<h3>6. Approvals, Inspections and Certification</h3>

<p>Approval time belongs in the plan, not in the contingency. Customer design reviews, quality documentation and third-party inspections all take calendar time, and all of them restart if the design changes after sign-off. Railway work is the clearest example: all our <a href="/products-railway-signalling-products/">railway signalling products</a> are inspected by RDSO at the plant before dispatch, so the inspection must be scheduled and the build must match the approved specification exactly. Our <a href="/blog/rdso-approved-railway-motors-buyers-guide/">buyer's guide to RDSO-approved railway motors</a> explains what to prepare.</p>

<h3>7. Long-Lead Bought-Out Parts and Tooling</h3>

<p>Magnets, gear sets, electromagnetic brakes, encoders, special bearings and connectors are usually bought-out items. Magnets cannot be substituted casually, because flux density sets the motor constant and coercivity sets resistance to demagnetisation; both are checked as part of PMDC motor testing at our Killa Pardi plant. New tooling for laminations or housings adds its own calendar. The practical remedy is staged release: once the parameters that govern a part are frozen (magnet grade and stack length, gear ratio, brake torque), that part can be ordered while details such as the connector are still being settled.</p>

