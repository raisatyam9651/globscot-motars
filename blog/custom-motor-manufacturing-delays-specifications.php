<h2>The Specification Freeze Checklist: What to Finalise Before Samples</h2>

<p>A specification freeze is the point after which the motor's defining parameters stop changing without a formal change request. It does not forbid change; it makes every change visible, costed and scheduled. The table shows what to fix and when.</p>

<div class="table-responsive">
<table class="table table-bordered table-hover" style="margin: 25px 0;">
