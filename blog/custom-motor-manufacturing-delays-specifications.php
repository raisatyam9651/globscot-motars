<strong>Design Guidance:</strong><br/>
If a parameter sets the winding, magnet or gear design, freeze it before design starts. If it appears anywhere on the motor drawing or the test sheet, freeze it before samples are built.
</div>

<p>The information needed for the very first enquiry is listed in our <a href="/blog/custom-motor-specification-checklist-first-call/">custom motor specification checklist for the first call</a>; the freeze is the step that turns that list into a signed, revision-controlled document. Sign the frozen specification and the test plan together, so that the drawing, the test sheet and the purchase order all refer to the same revision.</p>

