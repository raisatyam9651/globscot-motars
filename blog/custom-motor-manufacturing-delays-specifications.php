<h2>How to Keep a Custom Motor Project on Schedule</h2>

<ul>
<li><strong>Appoint one technical owner.</strong> One person on the buyer's side holds the specification; changes from purchasing, design and quality all go through that person.</li>
<li><strong>Agree the validation plan with the quotation.</strong> List each test, its conditions, pass criteria and who performs it before samples are built.</li>
<li><strong>Order enough samples for every test.</strong> Endurance, temperature-rise, in-machine and destructive tests each need units; a second build just for quantity is an avoidable loop.</li>
<li><strong>Use a formal change request.</strong> Every post-freeze change gets a short impact note covering cost, re-testing and schedule before it is accepted.</li>
<li><strong>Release long-lead parts in stages.</strong> Order magnets, gear sets and brakes as soon as the parameters that govern them are fixed.</li>
<li><strong>Book approvals early.</strong> Put customer sign-off meetings and any third-party inspection in the plan from day one.</li>
</ul>

<p>For replacement projects, capture the old motor's data in full before it leaves service; our guide to <a href="/blog/discontinued-motor-replacement-selection-guide/">discontinued motor replacement</a> lists what to measure.</p>

<hr/>

<h2>Frequently Asked Questions (FAQ)</h2>

<h3>Q1. How long does it take to develop a custom motor?</h3>
<p>There is no honest single figure until the specification is frozen. Calendar time depends on the stages the project must pass through, namely design, samples, validation, approval and production ramp, and above all on how many late changes send it back through samples and validation. A modified standard frame moves fastest; anything needing new laminations, housings or a third-party inspection takes longer. Ask for separate sample and series dates quoted against your frozen specification.</p>

<h3>Q2. What is a specification freeze in motor development?</h3>
<p>A specification freeze is the agreed point after which the motor's defining parameters stop changing without a formal change request. It covers load and duty, the supply voltage range, mounting and shaft, connections, options and acceptance tests. It is normally set before samples are built, because every parameter on the drawing or test sheet shapes the sample. Later changes remain possible, but each is assessed for cost, re-testing and schedule before acceptance.</p>

<h3>Q3. Why do custom motor samples fail customer validation?</h3>
<p>Most failures are specification gaps rather than build defects. Typical examples are a real duty cycle heavier than the one quoted, a supply voltage that sags well below its nominal figure, an overhung or shock load nobody mentioned, or a customer test run under different conditions from the factory test. Agreeing the load data, the voltage range and a written test method before samples removes most of these surprises.</p>

<h3>Q4. What should an RFQ for a custom motor include?</h3>
<p>At minimum: load torque and speed at the output, the duty cycle, the real supply voltage range at the motor terminals, the space envelope, mounting and shaft details, and annual volume. Then add the environment and IP rating, connector and lead requirements, options such as brakes or encoders, and the acceptance tests you will apply. Our <a href="/blog/custom-motor-specification-checklist-first-call/">custom motor specification checklist</a> lists each item in order of importance.</p>

<h3>Q5. Does RDSO inspection add time to railway motor orders?</h3>
<p>It adds a planned step rather than an unpredictable delay. All Globe Scott <a href="/products-railway-signalling-products/">railway signalling products</a> are inspected by RDSO at the plant before dispatch, so the inspection has to be scheduled into the delivery plan and the build must match the approved drawing and specification exactly. Late design changes on railway products are especially costly because the change itself may need fresh approval before supply can continue.</p>

<h3>Q6. Can a custom motor project be fast-tracked?</h3>
<p>Yes, mostly by removing loops rather than compressing manufacturing. Freeze the specification before samples, agree the validation plan and sample quantity in advance, release long-lead items such as magnets, gear sets, brakes and encoders as soon as their governing parameters are fixed, and route every later change through a formal impact review. Starting from an existing frame and modifying the winding, shaft or flange is also far quicker than new tooling.</p>

<hr/>

<h2>Conclusion and Engineering Next Steps</h2>

<p>Custom motor projects run late for predictable reasons: incomplete duty data, voltage quoted as a single number, mechanical and connector details settled after samples, tests nobody agreed and approvals nobody planned. Each one adds a loop of redesign, sampling and validation. Freezing the parameters in this guide before samples, and controlling every later change, removes most of those loops.</p>

