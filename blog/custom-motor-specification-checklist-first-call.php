<p>The difference between a quotation that comes back in days and one that takes three rounds of email is almost never the manufacturer. It is what was in the first message.</p>

<p>Below is what we actually need to design and price a custom motor, in the order it matters. Bring these to the first call and the engineering conversation starts immediately instead of beginning with a questionnaire.</p>

<h2>The Five Numbers Every Quote Request Needs on Day One</h2>

<h3>1. Load Torque at the Output Shaft</h3>
<p>Not motor torque, output torque, in newton metres. This is the number the machine actually demands. If you know force and radius instead, send those. If you only know the load being lifted or moved, send the mass, the geometry and the friction estimate and we will work it out. Our <a href="/blog/motor-torque-and-speed-calculation-practical-guide-industrial-applications/">practical torque and speed calculation guide</a> covers the arithmetic if you want to do it first.</p>

<h3>2. Required Output Speed</h3>
<p>In RPM at the output. Together with torque this fixes output power, which is the first thing that determines frame size. Where speed varies, give the range and the point at which peak torque occurs, because they are frequently not the same point.</p>

<h3>3. Supply Voltage</h3>
<p>Nominal, plus the real minimum and maximum. Battery systems in particular sag heavily under load, and a winding designed for 24 V nominal behaves differently on a pack that drops to 20 V at peak current. Our permanent magnet range covers 12 V DC to 220 V DC, so we can wind to almost any supply, but only if we know the real one.</p>

<h3>4. Duty Cycle</h3>
<p>Stated as an IEC duty class where possible: S1 continuous, S2 short-time, or S3 intermittent periodic with a duty ratio. If you do not know the class, send the pattern in plain terms, such as "runs 20 seconds, rests 4 minutes, all day". This single item changes thermal design more than anything else on the list.</p>

<h3>5. Space Envelope</h3>
<p>Maximum overall length, maximum diameter or square section, and any obstruction in the way of the shaft or the terminal box. It is far cheaper to design within the envelope than to discover it at first article.</p>

<h2>Duty Cycle and Ambient: Why These Change the Design</h2>

<p>These two decide whether a given frame works at all, and they are the pair most often left out.</p>

<p><strong>Ambient temperature at the motor</strong>, not in the room. A motor inside a sealed cabinet lives in the cabinet's air. Standard ratings assume 40 &deg;C, and every degree above that comes straight out of the thermal budget set by the insulation class, as explained in <a href="/blog/motor-insulation-classes-explained-class-f-vs-class-h/">motor insulation classes explained</a>.</p>

<p><strong>Duty class</strong> determines how much of the frame's thermal capacity you are allowed to use. An S3 intermittent rating lets a frame deliver considerably more peak power than the same frame on S1 continuous duty, because it has rest periods to shed heat. Specifying S1 when the machine is genuinely S3 buys a larger, heavier and more expensive motor than you need. Specifying S3 when the duty is really continuous produces a motor that overheats in service.</p>

<p>Also tell us about:</p>

<ul>
<li><strong>Ingress and environment.</strong> Wash-down, dust, outdoor exposure, humidity, salt. Our standard series run IP20 to IP44, with sealed builds available where the environment demands it. See <a href="/blog/ip67-motors-for-railway-applications-benefits-protection-performance/">IP67 motors and what protection levels buy you</a>.</li>
<li><strong>Orientation.</strong> Horizontal, shaft-up or shaft-down changes thrust loading and lubrication behaviour.</li>
<li><strong>Starting frequency.</strong> Starts per hour matters as much as running time on high-inertia loads.</li>
<li><strong>EMC constraints.</strong> If the product must pass emissions testing, say so now. EMI suppression filters are standard in many of our motors and can be fitted to any build.</li>
</ul>

<h2>Mounting and Shaft Details That Matter</h2>

<p>These are the items that cause redesign when they arrive late.</p>

<table class="table table-bordered table-striped">
<thead>
<tr><th>Item</th><th>What to Send</th></tr>
</thead>
<tbody>
<tr><td>Mounting type</td><td>B3 foot, B5 flange or B14 face</td></tr>
<tr><td>Register / spigot</td><td>Diameter and depth</td></tr>
<tr><td>Bolt pattern</td><td>Pitch circle diameter, hole count, clearance or thread size</td></tr>
<tr><td>Shaft</td><td>Diameter, extension length, tolerance</td></tr>
<tr><td>Shaft features</td><td>Keyway dimensions, flat, thread, or pinion detail</td></tr>
<tr><td>Coupling method</td><td>Direct, belt, chain, or gear, plus any overhung load</td></tr>
<tr><td>Cable exit</td><td>Position, length, connector type</td></tr>
</tbody>
</table>

<p>Overhung load is worth calling out specifically, because it is invisible on an electrical specification and it is what quietly destroys bearings. Our article on <a href="/blog/motor-mounting-configurations-explained/">motor mounting configurations</a> covers the load paths in detail.</p>

<h2>Options to Decide Early</h2>

<p>Anything integrated into the motor is cheaper to design in than to add later. Tell us at enquiry stage if you need an electromagnetic brake, an encoder or speed and position sensor, a reduction gearbox, EMI suppression filters, or incorporated or separate electronic controls. If a gearhead is involved, the ratio should be selected alongside the motor rather than afterwards, as covered in <a href="/blog/custom-geared-pmdc-motors-gear-ratio-torque-selection/">selecting gear ratio and torque for custom geared PMDC motors</a>. For traction-style drives, the <a href="/products-pmdc-transaxle/">PMDC transaxle range</a> may replace the motor-plus-gearbox question entirely.</p>

<h2>Commercial Information That Shapes the Answer</h2>

<ul>
<li><strong>Annual volume and call-off pattern.</strong> Determines whether new tooling is justified.</li>
<li><strong>Prototype date and series start date.</strong> These are different milestones with different drivers, as explained in <a href="/blog/motor-manufacturing-lead-times-explained/">what actually drives motor manufacturing lead times</a>.</li>
<li><strong>Target cost.</strong> Not to negotiate against, but because it decides which trade-offs are worth proposing.</li>
<li><strong>Certification needs.</strong> CE conformity, test certificates or specific documentation should be stated now rather than retro-fitted to a finished batch.</li>
</ul>

<h2>What a Typical Custom-Spec Timeline Looks Like</h2>

<ol>
<li><strong>Enquiry with the data above.</strong> Our applications team confirms feasibility and flags anything that needs a decision.</li>
<li><strong>Design modelling.</strong> Performance is analysed in our own motor design program before anything is cut, so major characteristics are known in advance.</li>
<li><strong>Preliminary quotation.</strong> Issued with complete performance data and a CAD-generated dimensional drawing, so your mechanical team can check fit before committing.</li>
<li><strong>Prototype.</strong> Typically available within a few weeks of specification freeze.</li>
<li><strong>Validation and approval.</strong> You fit and test; we adjust if required.</li>
<li><strong>Series production.</strong> Every unit dynamometer tested with horsepower and efficiency verified, as described in <a href="/blog/electric-motor-testing-standards-before-a-unit-ships/">our motor testing sequence</a>.</li>
</ol>

<p>Background on the capability behind this is on our <a href="/electromechanical-integrity/">electromechanical integrity page</a> and in <a href="/blog/importance-of-customization-in-pmdc-motor-design/">the case for customisation in PMDC motor design</a>.</p>

<hr/>

<h2>Frequently Asked Questions</h2>

<h3>Q1. What information do I need to request a custom motor quote?</h3>
<p>At minimum: load torque at the output shaft, required output speed in RPM, supply voltage including its real minimum and maximum, duty cycle, and the space envelope available. Ambient temperature, mounting configuration and shaft details should follow immediately after.</p>

<h3>Q2. Why does duty cycle matter so much in a motor specification?</h3>
<p>Duty class determines how much of the frame's thermal capacity you may use. An intermittent S3 rating allows considerably more peak power from the same frame than continuous S1 duty because rest periods let heat dissipate. Getting it wrong produces either an oversized motor or one that overheats.</p>

<h3>Q3. What is the difference between S1, S2 and S3 duty?</h3>
<p>S1 is continuous running at constant load until thermal equilibrium. S2 is short-time duty where the motor runs for a defined period then cools fully. S3 is intermittent periodic duty, a repeating run and rest pattern expressed as a duty ratio. Our standard PMDC frames are rated for all three.</p>

<h3>Q4. Do I need to know the motor torque or the load torque?</h3>
<p>Send the load torque at the output shaft. We will work back through gear ratio and efficiency to the motor rating. If you only know the mass being moved and the geometry, send those instead and we will calculate it.</p>

<h3>Q5. Which mounting dimensions should I include?</h3>
<p>Mounting type (B3 foot, B5 flange or B14 face), register diameter and depth, bolt pitch circle diameter with hole size or thread, shaft diameter and extension length, keyway or flat details, cable exit position, and any overhung load from a pulley or sprocket.</p>

<h3>Q6. How soon will I get a drawing?</h3>
<p>Preliminary quotations are issued with complete performance data and a CAD-generated dimensional drawing, so mechanical fit can be checked before any order is placed. Prototypes are typically available within a few weeks of specification freeze.</p>

<h3>Q7. What if I do not have all this information yet?</h3>
<p>Send what you have. Load torque, speed and voltage are enough to start a useful conversation, and our applications team will help you establish the rest. The checklist exists to shorten the cycle, not to gatekeep the enquiry.</p>

<h3>Q8. Should I mention certification requirements upfront?</h3>
<p>Yes. CE conformity, test certificates and specific documentation are far easier to produce inline than to retro-fit to a completed batch. Our quality system is ISO 9001:2015 certified and we hold CE marking for the low voltage range.</p>

<hr/>

<h2>Conclusion</h2>
<p>A custom motor enquiry lives or dies on five numbers: output torque, output speed, supply voltage, duty cycle and envelope. Add ambient temperature, mounting details and any integrated options, and a manufacturer can go straight to design work.</p>
<p>Everything left out becomes a question, and every question is a round trip. Bring the list and the first quotation will usually be close enough to build against.</p>

