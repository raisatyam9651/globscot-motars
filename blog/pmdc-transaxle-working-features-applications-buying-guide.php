<h2>3. Frequently Asked Questions (FAQs)</h2>

<h3>Q1: What are the main benefits of a PMDC transaxle over a hub motor?</h3>
<p>PMDC transaxles provide gear reduction torque multiplication and a mechanical differential, making them superior for climbing inclines and hauling heavy loads compared to direct-drive hub motors.</p>

<h3>Q2: Can a PMDC transaxle be disengaged for manual pushing?</h3>
<p>Yes. Quality transaxles include a manual freewheel disengagement lever that disengages internal gears so the vehicle can be pushed by hand when unpowered.</p>

<h3>Q3: What gear ratio is typical for electric wheelchair transaxles?</h3>
<p>Wheelchair and mobility scooter transaxles typically use gear reduction ratios between 20:1 and 28:1 to deliver 100–150 RPM at the drive wheels.</p>

<h3>Q4: How does the electromagnetic brake work on a PMDC transaxle?</h3>
<p>The brake is spring-applied and electrically released. When 24V DC is applied, the brake magnet releases; when power is cut, heavy springs engage the brake disc automatically.</p>

<h3>Q5: What payload weight can a 24V 400W PMDC transaxle haul?</h3>
<p>A quality 24V 400W PMDC transaxle can propel vehicles carrying total loads (vehicle + passenger/cargo) up to 300–400 kg across flat terrain and moderate ramps.</p>

<h3>Q6: Is synthetic grease used inside PMDC transaxle gearboxes?</h3>
<p>Yes. Transaxles are sealed with lifetime synthetic grease (Class NLGI 2), requiring zero periodic oil refilling.</p>

<h3>Q7: What maintenance is required for PMDC transaxles?</h3>
<p>Inspect carbon brushes every 2,000 operating hours, check wheel lug bolt tightness, and verify manual freewheel lever operation.</p>

