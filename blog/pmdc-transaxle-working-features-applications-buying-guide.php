<h2>1. How a PMDC Transaxle Works</h2>

<ol>
<li><strong>PMDC Motor Stage:</strong> High-efficiency permanent magnets generate field flux while armature current converts battery power (24V–48V DC) into high-speed rotation (3,000 RPM).</li>
<li><strong>Reduction Gear Train:</strong> Helical or spur gear stages reduce RPM (typically 15:1 to 30:1 ratio) while multiplying output axle torque.</li>
<li><strong>Differential Unit:</strong> Bevel or planetary differential gears distribute output torque to left and right drive wheels, allowing smooth differential rotation during cornering.</li>
<li><strong>Electromagnetic Brake:</strong> A rear-mounted 24V electromagnetic disc brake automatically locks the drive axle when power is disengaged, acting as a fail-safe parking brake.</li>
</ol>

