<h2>Frequently Asked Questions</h2>

<h3>Q1. What can be customised on a PMDC motor?</h3>
<p>Armature winding for a specific voltage and torque constant, output power within the frame's thermal limit, gear ratio, shaft diameter and length, keyway, mounting configuration, enclosure and ingress protection, plus fitted options such as electromagnetic brakes, encoders, EMI filters and electronic controls.</p>

<h3>Q2. Is a custom PMDC motor more expensive than a standard one?</h3>
<p>Per unit it can be slightly higher, but the comparison that matters is total installed cost. A correctly matched motor often removes a pulley reduction, a machined coupling or extra chassis volume, and it runs nearer its efficiency peak, which lowers running cost.</p>

<h3>Q3. How long does a custom PMDC motor design take?</h3>
<p>Preliminary performance data and CAD dimensional drawings are turned around quickly because the design is modelled in our own motor design program first. Prototypes are typically available within a few weeks; series lead time then depends on winding complexity and any new tooling.</p>

<h3>Q4. What is the minimum quantity for a customised motor?</h3>
<p>It depends on how much new tooling the design needs. Because we have an in-house tool room and flexible manufacturing, we execute both small and large requirements, and we often propose a standard frame with custom winding, shaft and mounting for lower volumes.</p>

<h3>Q5. Do you provide dimensional drawings before I commit?</h3>
<p>Yes. Preliminary quotations include complete performance data and CAD-generated dimensional drawings so your mechanical team can check the fit before any order is placed.</p>

<h3>Q6. Can you customise the gear ratio as well as the motor?</h3>
<p>Yes, and it is usually better to select both together. Standard ratios run from 9:1 up to 80:1 depending on frame, and the PMDC transaxle families use 7:1 and 10:1 with parallel-exit steel gears.</p>

<h3>Q7. Will a custom motor still be certified?</h3>
<p>Our quality system is ISO 9001:2015 certified and we hold CE marking for the low voltage range. Product certification, conformity certificates and test certificates are available on request for custom builds.</p>

<hr/>

<h2>Conclusion</h2>
<p>Customisation in PMDC motor design is not a premium add-on. It is the difference between a motor that fits your machine and a machine reshaped around a motor.</p>
<p>The variables worth changing are usually the winding, the gear ratio, the shaft and mounting, and the protection level, and all four can be settled before a prototype exists. Globe Scott Motors has been doing that from Killa Pardi since 1985, with in-house tooling, computer-aided design and dynamometer verification of every unit.</p>

