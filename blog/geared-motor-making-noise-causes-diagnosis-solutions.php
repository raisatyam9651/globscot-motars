<h2>Isolation Test: Motor, Gearbox, Drive or Machine?</h2>

<p>Run these steps before opening anything, keeping the meter at the same position about 1 m from the gearbox:</p>

<ol>
<li><strong>Isolate and lock out</strong>, then turn the output by hand: notchiness means tooth or bearing damage; free play at reversal measures backlash.</li>
<li><strong>Record a baseline</strong> level and spectrum, plus background with the machine stopped.</li>
<li><strong>Decouple the load</strong> and run at the same speed; if the noise goes, check the coupling and machine.</li>
<li><strong>Run from a clean DC source</strong> such as a battery; if a fixed-pitch tone goes, the drive is the source.</li>
<li><strong>Run the motor without the gearbox</strong> where the construction allows.</li>
<li><strong>Re-apply load, sweep speed and reverse direction</strong>, noting each change.</li>
</ol>

<p>If the motor alone measures 58 dB(A) and the complete geared motor 66 dB(A), the gearbox contributes:</p>

<div class="gsm-equation">\[ L_{gear} = 10\log_{10}\left(10^{66/10} - 10^{58/10}\right) \approx 65.3\,\mathrm{dB(A)} \]</div>

<p>The gearbox is almost the entire problem, so work on the motor would change little.</p>

