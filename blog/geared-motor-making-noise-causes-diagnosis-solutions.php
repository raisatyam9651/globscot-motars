<h2>Frequently Asked Questions (FAQ)</h2>

<h3>Q1. Is it normal for a geared motor to make some noise?</h3>
<p>Yes. Every gear mesh produces a steady hum because teeth deflect under load and engage at discrete intervals; small geared motors broadly measure around 50–70 dB(A) at 1 m depending on gear type, speed and mounting. What is not normal is change: a new tone, a clicking or knocking rhythm, or a sustained rise of 3 dB(A) or more over the as-installed baseline.</p>

<h3>Q2. Why does my gearbox whine more as the speed increases?</h3>
<p>A whine that rises in pitch with speed is gear mesh noise, because mesh frequency equals the number of teeth multiplied by the gear's revolutions per second. It grows louder when tooth profiles wear, backlash is wrong, shafts are misaligned by overhung load or the lubricant film is thin. Compare each stage's calculated mesh frequency with a spectrum reading to find the stage responsible.</p>

<h3>Q3. What causes a clicking or knocking noise in a gear motor?</h3>
<p>A regular click or knock usually comes from a chipped tooth, a damaged bearing, or backlash taken up when the load reverses. Count the clicks per second and compare with each shaft's rotational frequency: one click per output revolution points to the output gear. A knock only at reversal points to backlash, a loose key or a worn coupling rather than tooth damage.</p>

<h3>Q4. Can the wrong grease make a geared motor noisy?</h3>
<p>Yes. Grease that is too thin at operating temperature lets the film break down, causing whine and scuffing, while hardened or channelled grease leaves the gears running nearly dry. Mixed thickeners, monsoon water contamination and oxidation in hot summer ambients cause the same symptoms. Clean out the old lubricant and refill only with the grade the gearbox manufacturer specifies.</p>

<h3>Q5. Why does my DC gear motor whistle on a PWM speed controller?</h3>
<p>The whistle is the PWM switching frequency. When the controller switches within the audible band, current ripple creates small torque and magnetic forces at that frequency, radiated as a fixed-pitch tone that does not change with speed. Raising the carrier to about 16–20 kHz or above, or adding series inductance, normally removes it and also reduces gear rattle at low speed.</p>

<h3>Q6. Are worm gear motors quieter than spur gear motors?</h3>
<p>Generally, yes. A worm set transmits power through sliding contact at a low mesh frequency, so it produces less tonal noise than a spur set at the same input speed. Worm gears are, however, sensitive to contact pattern, bronze wheel wear and lubricant condition, and growl or squeal when these go wrong. For parallel-shaft drives, helical gears are the quieter alternative to spur.</p>

<h3>Q7. How do I tell whether the noise comes from the motor or the gearbox?</h3>
<p>Run the motor on its own, separated from the gearbox where the construction allows, at the same speed. If the noise disappears, the gearbox is responsible; if it remains, check the motor bearings, brushes and drive. Running from a battery instead of the PWM controller isolates drive noise, and decibel subtraction quantifies each source's contribution.</p>

<hr/>

<h2>Conclusion and Engineering Next Steps</h2>

<p>A noisy geared motor is giving you diagnostic data. Calculate the mesh and shaft frequencies, describe the sound by pitch and rhythm, and isolate motor, gearbox, drive and machine before replacing parts. Most problems trace back to lubrication, shaft loading, mounting stiffness or PWM frequency, and each has a specific, measurable fix.</p>

