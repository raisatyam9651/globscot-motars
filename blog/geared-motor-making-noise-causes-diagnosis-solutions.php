<h2>Lubrication, Mounting and Gear Type: What Amplifies Gear Noise</h2>

<p><strong>Lubrication.</strong> Common grease faults are channelling (gears cut a channel and run starved), hardening after long periods hot, loss through leaking seals, water emulsion in the monsoon, and mixing incompatible thickeners. Clean out the old lubricant completely and refill with the grade and quantity the gearbox maker specifies; overfilling adds churning heat.</p>

<p><strong>Mounting resonance.</strong> A gearbox bolted to a thin panel or long cantilever bracket turns it into a loudspeaker; the giveaway is noise that peaks sharply at one speed. Stiffen or damp the bracket, or shift the mesh frequency with a different speed or ratio, choosing any new ratio as described in our guide to <a href="/blog/dc-motor-gear-ratio-selection-speed-too-high/">DC motor gear ratio selection</a>.</p>

<p><strong>Gear type.</strong> Each architecture has its own noise character; our <a href="/blog/geared-pmdc-motor-working-benefits-applications-selection-guide/">geared PMDC motor guide</a> covers their wider trade-offs.</p>

