</tbody>
</table>
</div>

<div style="background: #e8f4f8; border: 1px solid #bee5eb; padding: 15px; border-radius: 6px; margin: 20px 0;">
<strong>Design Guidance:</strong><br/>
For new machines, specify noise as a measurable acceptance criterion: dB(A) at 1 m at stated speed, load and mounting, with the PWM frequency defined. A number agreed at the sample stage is far easier to verify than "quiet operation".
</div>

