<p>A gearbox that ran quietly for months and now whines, grinds or knocks is telling you something specific. When a <strong>geared motor making noise</strong> is reported from the shop floor, the sound itself is the quickest diagnostic instrument you have. Its pitch, its rhythm and the way it changes with speed, load and direction point to a short list of causes in the gear train, bearings, lubricant, mounting or drive electronics.</p>

<p>Noise is rarely just a nuisance. A rising mesh whine usually comes before measurable tooth wear, a new knock often means a damaged tooth or bearing, and a steady whistle that ignores speed is frequently not mechanical at all. The methods below apply to parallel-shaft, worm and planetary units such as our <a href="/products-geared-motors/">industrial geared motors</a> and the steel-geared, parallel-exit <a href="/products-pmdc-geared-motors/">PMDC geared traction motors</a> used in trolleys and small vehicles.</p>

<div class="alert alert-info gsm-quick-summary" style="background-color: #f0f7fd; border-left: 4px solid #0056b3; padding: 15px; margin: 25px 0;">
<strong>Quick Summary:</strong> Identify the noise by its signature before dismantling anything. A whine whose pitch rises with speed is gear mesh (wear, wrong backlash, misalignment, poor lubrication); grinding means tooth damage or contamination; a regular click or knock points to a chipped tooth, a bearing defect or backlash under reversing load; a low rumble is bearing wear; a fixed-pitch whistle is usually PWM switching in the audible band. Then isolate: run the motor decoupled, on a clean DC supply, and the gearbox under load.
</div>

<h2>What a Healthy Geared Motor Sounds Like</h2>

<p>Every gear mesh makes some noise. Teeth deflect under load and engage at discrete instants, so even a well-made gear set has a small periodic transmission error that the housing radiates as a steady hum. Broadly, small fractional-kilowatt geared motors measure somewhere in the 50–70 dB(A) region at 1 m: worm and helical sets towards the quieter end, spur gears at high input speed towards the louder end, with the mounting shifting the figure either way.</p>

<p>Because installation matters so much, your own as-installed baseline is the real benchmark. A rise of 3 dB doubles the radiated acoustic power; a rise of about 10 dB sounds roughly twice as loud. Levels from separate sources combine logarithmically:</p>

<div class="gsm-equation">\[ L_{total} = 10\log_{10}\left(\sum_{k} 10^{L_k/10}\right) \]</div>

<p>The same relation lets you subtract one source from another. A reading less than 3 dB above background cannot be separated from it reliably; background more than 10 dB lower can be ignored.</p>

<hr/>

<h2>Calculating the Frequencies Behind the Noise</h2>

<p>Matching a measured tone to a calculated frequency turns guesswork into diagnosis. The fundamental of gear noise is the gear mesh frequency:</p>

<div class="gsm-equation">\[ f_{mesh} = \frac{z \cdot N}{60} \]</div>

<p>where \( z \) is the number of teeth on either gear of the pair and \( N \) is that gear's speed in rpm. Each stage has its own mesh frequency, and each shaft its own rotational frequency \( f_s = N/60 \). A chipped tooth strikes once per revolution of its shaft, and an eccentric gear creates sidebands at \( f_{mesh} \pm f_s \). For a planetary stage with a fixed ring gear use \( f_{mesh} = z_{ring} N_{carrier}/60 \); for a worm, multiply the number of starts by the worm's revolutions per second.</p>

<h3>Worked Example: A Two-Stage 20:1 Spur Gearbox</h3>

<p>A 24 V PMDC geared motor runs at 3,000 rpm under load through a 12-tooth pinion driving a 48-tooth gear (4:1), then a 10-tooth pinion driving a 50-tooth gear (5:1).</p>

<div class="gsm-equation">\[ f_{mesh,1} = \frac{12 \times 3000}{60} = 600\,\mathrm{Hz}, \qquad N_2 = 3000 \times \frac{12}{48} = 750\,\mathrm{rpm} \]</div>

<div class="gsm-equation">\[ f_{mesh,2} = \frac{10 \times 750}{60} = 125\,\mathrm{Hz}, \qquad N_{out} = 750 \times \frac{10}{50} = 150\,\mathrm{rpm} \]</div>

<p>Shaft frequencies are 50 Hz, 12.5 Hz and 2.5 Hz. Suppose a spectrum shows a strong 600 Hz peak with sidebands 50 Hz either side, a knock about two and a half times per second, and a steady 4 kHz tone. The sidebands point to runout or wear on the motor pinion, the knock to a damaged tooth on the output gear, and the 4 kHz tone matches no gear or shaft, so it is almost certainly the PWM carrier.</p>

<div style="background: #fff3cd; border: 1px solid #ffeeba; padding: 15px; border-radius: 6px; margin: 20px 0;">
<strong>Field Rule of Thumb:</strong><br/>
If you can count the clicks, look at the slow shafts. A defect on the output gear gives a countable knock, one on an intermediate shaft sounds like a rattle, and one on the motor pinion blends into a buzz that only a spectrum will separate.
</div>

<hr/>

<h2>Six Sound Signatures of a Geared Motor Making Noise</h2>

<h3>1. A Whine That Rises With Speed: Gear Mesh Problems</h3>

<p>A tonal whine at a mesh frequency that grows louder over weeks is the classic sign of a degrading mesh. Typical causes are tooth wear and pitting; backlash that is too tight because of a wrong centre distance, thermal growth or plastic gears swollen by monsoon humidity; misalignment from a shaft deflected by overhung belt or sprocket load; and a thin lubricant film in 45–50 °C summer ambients.</p>
<h4>How to Diagnose It:</h4>
<p>Compare the spectrum peak with the calculated mesh frequencies to find the stage. A whine that grows with load suggests edge loading; one that grows as the unit warms suggests the lubricant.</p>
<h4>How to Fix It:</h4>
<p>Restore the specified lubricant, relieve the overhung load and replace worn gears as matched pairs. Where the tone is inherent to a spur stage at high input speed, a helical first stage or lower motor speed reduces it.</p>

<h3>2. Grinding or a Gritty Rasp: Tooth Damage and Contamination</h3>

<p>Grinding is broadband and rough. It comes from pitted or scuffed tooth flanks, or from hard particles in the grease: wear debris, ingested dust, or water that has emulsified the grease into a milky paste. With the supply isolated, a notchy feel when turning the output by hand confirms surface damage, and steel particles on a magnet confirm active wear. Replace the damaged gears and bearings, flush out all old lubricant, improve the sealing and find out why the teeth were overloaded.</p>

<h3>3. A Periodic Click or Knock: Chipped Teeth, Bearings and Backlash</h3>

<p>Count the events per second. A rate matching a shaft frequency points to a chipped tooth on that shaft; a rate that is not a whole multiple of any shaft speed points to a bearing defect. A knock only at reversal or start-stop points to backlash, a loose key or a worn coupling. Some backlash is normal, as our comparison of <a href="/blog/geared-motor-vs-standard-dc-motor-key-differences/">geared motors and standard DC motors</a> explains; growing backlash is not. A rattle at light load and low speed that vanishes under load is gear hammer: torque ripple exceeds the small mean load torque, so the teeth separate and re-strike.</p>

<h3>4. A Low Rumble or Growl: Bearing Wear and Overhung Load</h3>

<p>A non-tonal rumble that rises with speed and load, with one bearing housing warmer than the rest, indicates bearing wear. Bearing defect frequencies are not whole multiples of shaft speed; our guide to <a href="/blog/dc-motor-vibration-problems-how-to-identify/">DC motor vibration problems</a> covers them in detail. On output bearings the usual root cause is overhung load from an over-tensioned belt or a small sprocket mounted far from the housing. Replace the bearings, move the sprocket close to the housing, and check the radial load against the gearbox rating as described in our guide to <a href="/blog/motor-gearbox-sizing-problems-output/">motor gearbox sizing problems</a>.</p>

<h3>5. A Whistle That Does Not Change Pitch: PWM Switching Noise</h3>

<p>A PWM controller switches the armature voltage at a fixed carrier frequency. In the audible band, the current ripple produces small torque and magnetic forces at the carrier, radiated as a pure tone whose pitch stays constant while speed changes. For a single-switch chopper, or an H-bridge with only one leg switching:</p>

<div class="gsm-equation">\[ \Delta I_{pp} = \frac{V \cdot D(1-D)}{L \cdot f_{PWM}} \]</div>

<p>With 24 V, 1 mH of armature inductance and 50 % duty, a 4 kHz carrier gives \( \Delta I_{pp} = 24 \times 0.25/(0.001 \times 4000) = 1.5\,\mathrm{A} \); at 20 kHz it falls to 0.3 A. Raising the carrier to about 16–20 kHz or above moves the tone beyond most adults' hearing and cuts ripple five-fold, which also calms gear hammer. Confirm the driver's switching losses and EMC stay acceptable, or add a series choke. Where low noise is a design requirement, our <a href="/products-bldc-motors/">BLDC motors</a> with sinusoidal FOC drivers remove brush noise and much of the torque ripple.</p>

<h3>6. Hiss, Squeal or Scrape at the Motor End: Brushes and Brake</h3>

<p>A soft brush hiss is normal in a PMDC motor. A squeal appears while new brushes bed in or when the commutator film is glazed; chatter points to high mica or an out-of-round commutator, covered in our <a href="/dc-motor-maintenance/">DC motor maintenance guide</a>. On brake-equipped units, a scrape at motor speed usually means the electromagnetic brake is not fully releasing: check the coil voltage at its terminals and the air gap.</p>

