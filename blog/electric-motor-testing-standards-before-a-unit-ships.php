<h2>Frequently Asked Questions</h2>

<h3>Q1. What testing does an electric motor go through before shipping?</h3>
<p>At Globe Scott Motors the sequence is incoming magnet testing for residual flux density and coercive force, ultrasonic flaw detection on every magnet, armature testing on the machine during assembly, full dynamometer performance testing of every motor with horsepower and efficiency verified, and endurance testing at rated load to evaluate bearing and brush life.</p>

<h3>Q2. Is every motor tested, or only a sample?</h3>
<p>Every motor is tested on the dynamometer and its horsepower and efficiency are verified. Every magnet is also individually screened with an ultrasonic flaw detector before assembly. These are 100 percent checks, not sampled ones.</p>

<h3>Q3. Why is magnet testing so important in a permanent magnet motor?</h3>
<p>The magnets supply the field, so their properties directly set the motor's torque and speed constants. Variation in magnetic properties produces intolerable variation in motor specifications, which is why total flux is held near constant across batches by testing residual flux density and coercive force.</p>

<h3>Q4. What does ultrasonic flaw detection find that other tests miss?</h3>
<p>Internal cracks and porosity inside a magnet, which are often introduced during shipping. Such a magnet looks perfect, assembles normally and passes electrical test, then causes inconsistent performance or outright failure in the field. Nothing downstream reliably catches it.</p>

<h3>Q5. What is the difference between a no-load test and a dynamometer test?</h3>
<p>A no-load test confirms the motor turns and shows friction and windage. A dynamometer test loads the motor under actual operating conditions, which is the only way to verify torque constant, torque-speed slope, horsepower at the rated point, real efficiency and thermal behaviour under load.</p>

<h3>Q6. What is endurance testing and why does it matter?</h3>
<p>The motor is run continuously at rated load to evaluate bearing and brush life. Because it runs loaded rather than free, it reproduces genuine field wear on brushes, commutator and bearings, which is how real service life is established rather than estimated.</p>

<h3>Q7. Can you provide test certificates with an order?</h3>
<p>Yes. Conformity and test certificates are available on request, and product certification can be arranged. State the requirement at enquiry stage, because producing documentation inline with manufacture is far easier than reconstructing it for a completed batch.</p>

<h3>Q8. What quality certifications does Globe Scott Motors hold?</h3>
<p>ISO 9001:2015 certification for the quality management system and CE marking for the low voltage range of motors. We are also registered with NSIC, hold a CRISIL performance and credit rating, and are an approved supplier to Indian Railways.</p>

<hr/>

<h2>Conclusion</h2>
<p>A credible testing claim is specific. It names the stage, the parameter, the instrument and whether the check runs on every unit or on a sample. Ours runs from magnet flux and ultrasonic screening at goods-in, through armature testing during assembly, to dynamometer verification of every motor and endurance testing at rated load.</p>
<p>Use the six questions above on any supplier you are evaluating, including us. The answers will tell you considerably more than a quality statement.</p>

