<p>"We test everything" is the least informative sentence in a supplier presentation. Any quality-minded buyer wants the actual sequence: what is checked, at which stage, on every unit or on a sample, and what happens when something fails.</p>

<p>This is that sequence as it runs at our Killa Pardi plant. It is worth reading even if you buy elsewhere, because it gives you the questions to put to any motor supplier.</p>

<h2>Stage 1: Incoming Material Inspection</h2>

<p>In a permanent magnet machine, the magnets <em>are</em> the field. Get them wrong and every downstream measurement inherits the error, so incoming inspection carries more weight here than in a wound-field design. Two checks run before a magnet enters the process.</p>

<h3>Magnet Characteristic Testing</h3>
<p>Variation in magnetic properties produces intolerable variation in motor specifications. To hold motor performance inside a narrow band, the total flux of the magnets used has to be kept near constant, so we test the critical parameters with dedicated instrumentation:</p>

<ul>
<li><strong>Residual flux density (B<sub>r</sub>)</strong>, which sets how much field the magnet delivers and therefore the motor's torque constant.</li>
<li><strong>Coercive force (H<sub>c</sub>)</strong>, which sets how strongly the magnet resists demagnetisation under armature reaction and elevated temperature.</li>
</ul>

<p>A batch that drifts on either parameter produces motors that are individually functional and collectively inconsistent, which is the failure mode that most annoys an OEM assembling to a fixed control setting.</p>

<h3>Ultrasonic Flaw Detection</h3>
<p>Magnets can carry internal cracks and porosity, and cracks are frequently introduced in transit rather than in manufacture. An internally cracked magnet passes visual inspection, assembles normally and then fails in the field. We run <strong>every magnet</strong> through an ultrasonic flaw detector before it goes into a motor.</p>

<p>This is the check most often skipped elsewhere, because it is slow and it rejects parts that look perfect. It is also the check that prevents a class of field failures nothing downstream would catch. Both stages are described on our <a href="/electromechanical-integrity/">electromechanical integrity page</a>.</p>

<h2>Stage 2: In-Process Checks During Winding and Assembly</h2>

<p>Armature testing on the machine happens while the rotor is still accessible. The point is to catch winding and commutator faults before the motor is closed up, because a defect found at final test costs a full teardown while the same defect found at winding costs a rework.</p>

<p>Assembly-stage attention goes to the things that determine mechanical life: concentricity through press fits, bearing seating, magnet placement without chipping, and brush gear alignment so that the brushes bed evenly on the commutator. Uneven bedding is a common root cause of the premature wear discussed in <a href="/blog/brushed-vs-brushless-motor-maintenance-comparison/">the brushed versus brushless maintenance comparison</a>.</p>

<h2>Stage 3: Final Performance Test on the Dynamometer</h2>

<p>This is the stage that separates a verified motor from a motor that merely turns.</p>

<p>Our factory has a full testing facility including a <strong>back-to-back testing arrangement</strong> and an <strong>eddy-current dynamometer</strong>. That lets us load the motor under genuine operating conditions rather than inferring performance from a no-load spin.</p>

<p><strong>Every single motor is tested on the dynamometer, and horsepower and efficiency are verified.</strong> Not a sample, not a batch representative. Every unit.</p>

<p>What a loaded test establishes that a no-load test cannot:</p>

<table class="table table-bordered table-striped">
<thead>
<tr><th>Measurement</th><th>What It Confirms</th></tr>
</thead>
<tbody>
<tr><td>No-load current and speed</td><td>Friction, windage and magnetic circuit are within expectation</td></tr>
<tr><td>Load torque versus current</td><td>Torque constant is correct, so the magnetic circuit is right</td></tr>
<tr><td>Speed under load</td><td>Torque-speed slope matches design; armature resistance is correct</td></tr>
<tr><td>Horsepower at rated point</td><td>The motor genuinely meets its nameplate</td></tr>
<tr><td>Efficiency</td><td>Total losses are within design, not merely that the unit runs</td></tr>
<tr><td>Temperature during run</td><td>Thermal behaviour is consistent with the insulation class</td></tr>
</tbody>
</table>

<p>Because efficiency is measured rather than calculated, the figures we quote come from a dynamometer. That distinction matters when comparing suppliers, as discussed in <a href="/blog/motor-efficiency-ratings-explained-for-equipment-buyers/">motor efficiency ratings explained for equipment buyers</a>.</p>

<h2>Stage 4: Endurance Testing</h2>

<p>Performance testing tells you what a motor does today. Endurance testing tells you what it will do in two years.</p>

<p>Motors are run continuously at rated load to evaluate the life of bearings and brushes. Because the run is at load rather than free-spinning, it reproduces the real wear mechanisms: brush face wear against the commutator, commutator surface development, bearing behaviour at working temperature, and the thermal cycling that ages insulation.</p>

<p>This is where a design's real service life is established rather than estimated, and where brush grade selection for a particular duty gets validated. The wear mechanisms it exposes are described in <a href="/blog/dc-motor-maintenance-common-problems-troubleshooting-preventive/">common DC motor problems and preventive maintenance</a> and the thermal side in <a href="/blog/motor-insulation-classes-explained-class-f-vs-class-h/">motor insulation classes explained</a>.</p>

<h2>Stage 5: Documentation and Traceability</h2>

<p>Testing that is not recorded is not evidence. Our quality management system is certified to <strong>ISO 9001:2015</strong>, and we hold <strong>CE marking</strong> for the low voltage range of motors. Conformity certificates and test certificates are available on request, and product certification can be arranged where a programme requires it.</p>

<p>Our test laboratory is equipped with a computerised data acquisition system, and lifetime and mechanical stress tests can be carried out there as part of a development programme rather than only as production verification.</p>

<p>For buyers who need documentation, the practical advice is to state the requirement at enquiry stage. Producing certificates inline with manufacture is straightforward; reconstructing them for a completed batch is not. The full enquiry checklist is in <a href="/blog/custom-motor-specification-checklist-first-call/">what to bring to your first custom motor call</a>, and how this affects scheduling is covered in <a href="/blog/motor-manufacturing-lead-times-explained/">what actually drives motor manufacturing lead times</a>.</p>

<h2>Design Verification Before Any of This</h2>

<p>One stage sits upstream of production testing. We maintain an exclusive motor design computer program in which all major aspects of performance are analysed and evaluated before the initial stage of product development. Preliminary quotations therefore include complete performance data and CAD-generated dimensional drawings, and prototypes follow within a few weeks. Catching a magnetic circuit error in software is considerably cheaper than catching it on a dynamometer.</p>

<h2>Six Questions to Ask Any Motor Supplier</h2>

<ol>
<li>Are incoming magnets tested for residual flux density and coercive force, or accepted on a supplier certificate?</li>
<li>Is every magnet screened for internal cracks, or is this sampled?</li>
<li>Is every motor dynamometer tested under load, or is a sample tested and the rest spun no-load?</li>
<li>Is quoted efficiency measured or calculated from design software?</li>
<li>Is endurance testing run at rated load, and for how long?</li>
<li>Can you supply conformity and test certificates traceable to my batch?</li>
</ol>

<p>These distinguish suppliers far more effectively than a general claim about quality. For the wider evaluation framework see our <a href="/blog/select-industrial-motor-manufacturer-in-india-custom-requirements/">guide to selecting an industrial motor manufacturer in India</a>, the context behind our own process in <a href="/blog/made-in-india-since-1985-motor-reliability/">what four decades of manufacturing actually means for reliability</a>, and the <a href="/case-study/">Indian Railways supply case study</a> for an example at scale. Product ranges are on our <a href="/products/">main products page</a>.</p>

