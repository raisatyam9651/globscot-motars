<h2>How a Custom Programme Runs</h2>

<p>We maintain an exclusive motor design computer program, so major performance aspects are analysed before the first prototype is cut. Preliminary quotations come back with complete performance data and CAD-generated dimensional drawings, and prototypes are typically available within a few weeks. Every finished motor is then run on a dynamometer with horsepower and efficiency verified, as described on our <a href="/electromechanical-integrity/">electromechanical integrity and testing page</a>.</p>

<p>If you are preparing an enquiry, the checklist in <a href="/blog/custom-motor-specification-checklist-first-call/">what to bring to your first custom motor call</a> will shorten the quotation cycle considerably. If you are still comparing suppliers, our <a href="/blog/select-industrial-motor-manufacturer-in-india-custom-requirements/">guide to selecting an industrial motor manufacturer in India</a> sets out the questions worth asking.</p>

