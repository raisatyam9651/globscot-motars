<h2>Frequently Asked Questions</h2>

<h3>Q1. What makes Globe Scott Motors a leading custom PMDC motor manufacturer in India?</h3>
<p>Globe Scott Motors introduced the permanent magnet DC motor to India in 1985 and has manufactured it continuously in the same Killa Pardi plant since. The combination of an in-house tool room, an exclusive motor design program, full dynamometer testing of every unit and ISO 9001:2015 certification lets us build to a customer drawing rather than force a redesign around a stock frame.</p>

<h3>Q2. What power and voltage range do your custom PMDC motors cover?</h3>
<p>Our permanent magnet DC range covers 25 W to 3000 W, with supply voltages from 12 V DC to 220 V DC and S1, S2 and S3 duty classifications. Standard protection class is IP20 to IP44, with sealed builds available for wash-down and outdoor applications.</p>

<h3>Q3. Can you supply a motor with an integrated gearbox and brake?</h3>
<p>Yes. Reduction gears, electromagnetic brakes, encoders, speed and position sensors, EMI suppression filters and electronic controls can all be fitted. Our PMDC geared motor and transaxle families are built specifically around integrated gear and brake packages.</p>

<h3>Q4. How long does a custom PMDC motor prototype take?</h3>
<p>Preliminary quotations including performance data and CAD dimensional drawings are turned around quickly, and prototypes are typically available within a few weeks. Series lead time depends on winding complexity and whether the configuration is a stock variant or a fully custom build.</p>

<h3>Q5. Do you export custom motors outside India?</h3>
<p>Yes. Around 45% of our DC motors and gearboxes are exported to Europe. We hold CE marking for the low voltage range and can supply conformity and test certificates on request.</p>

<h3>Q6. Are you an approved supplier for Indian Railways?</h3>
<p>Yes. Globe Scott Motors is an approved supplier to Indian Railways for point machine motors, point machine systems and electric lifting barriers. Our railway signalling product range is documented separately.</p>

<h3>Q7. What is the minimum order quantity for a custom motor?</h3>
<p>Because we have our own tool room and flexible manufacturing, we can execute both small and large requirements. The practical minimum depends on how much new tooling a design needs, which we confirm at the quotation stage.</p>

<h3>Q8. Where is your manufacturing facility located?</h3>
<p>Our plant is at A1/19, G.I.D.C. Industrial Estate, Killa Pardi 396125, Gujarat, India. Design, tooling, winding, assembly and testing all happen at this single site.</p>

<hr/>

<h2>Conclusion</h2>
<p>A custom motor programme succeeds or fails on how well the manufacturer understands the machine the motor goes into. Globe Scott Motors has spent four decades building permanent magnet DC motors to customer drawings for Indian and European OEMs, backed by in-house tooling, computer-aided design and dynamometer verification of every unit shipped.</p>
<p>Send us your duty cycle, torque requirement, envelope and supply voltage, and our application engineering team will come back with performance data and a dimensional drawing.</p>

