<h2>Planning Mistakes Beyond the First Purchase Order</h2>

<h3>Mistake 8: Unmanaged Single-Source Risk</h3>

<p>Single-sourcing a custom motor is often sensible, because qualification and tooling are expensive to duplicate. The mistake is single-sourcing without a plan. Hold safety stock sized to the supplier's replenishment time, ask which bought-out parts such as magnets, bearings and gear sets the supplier itself depends on, check its quality system and track record, and keep the interface drawing current so that a second source could be qualified. Our article on <a href="/blog/made-in-india-since-1985-motor-reliability/">what four decades of motor manufacturing means for reliability</a> covers how to judge supplier continuity.</p>

<h3>Mistake 9: Overlooking Packaging, Logistics and Storage</h3>

<p>Motors that leave the factory in good condition can still arrive damaged or corroded. Monsoon humidity and container condensation attack bright shafts and lamination edges, and heavy geared units crush weak cartons when stacked. Specify the packaging: shaft protection, volatile corrosion inhibitor (VCI) film or sealed bags with desiccant, carton strength and stacking limits, and labels carrying lot and date codes for traceability. Agree storage rules too, such as first-in-first-out issue and a maximum shelf time before re-inspection.</p>

<h3>Mistake 10: No Lifecycle or Obsolescence Plan</h3>

<p>An OEM machine may be sold for years and serviced for longer still. Agree spare-motor availability, advance notice of discontinuation, a last-time-buy window and the documentation needed to make an equivalent later. If you are already facing that situation, our guide to <a href="/blog/discontinued-motor-replacement-selection-guide/">discontinued motor replacement</a> explains what to capture from the original. Wider customisation choices are covered in our sibling guide to <a href="/blog/custom-motor-design-non-standard-sizes/">custom motor design for non-standard sizes</a>.</p>

