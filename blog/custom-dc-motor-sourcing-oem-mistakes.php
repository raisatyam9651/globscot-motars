<p>Supplier A's apparent saving of ₹800 per motor, or ₹8 lakh a year, becomes a ₹95 per motor penalty once quality costs are counted. The machine owner sees a further difference. Energy cost per year is:</p>

<div class="gsm-equation">\[ C_{energy} = \frac{P_{out}}{\eta} \cdot h \cdot c_{kWh} \]</div>

<p>If A's motor is 76 % efficient and B's 80 %, running 4,000 hours a year at ₹8 per kWh, A draws \( 500/0.76 \approx 658\,\mathrm{W} \) and costs about ₹21,050 a year to run, against \( 500/0.80 = 625\,\mathrm{W} \) and ₹20,000 for B. That is roughly ₹1,050 more every year, more than the original price difference. Efficiency claims should therefore be verified at the working load point, as explained in our guide to <a href="/blog/motor-efficiency-ratings-explained-for-equipment-buyers/">motor efficiency ratings for equipment buyers</a>.</p>

<div style="background: #fff3cd; border: 1px solid #ffeeba; padding: 15px; border-radius: 6px; margin: 20px 0;">
<strong>Procurement Rule of Thumb:</strong><br/>
Divide the price difference by the cost of one field failure. Here, ₹800 ÷ ₹25,000 = 3.2 %. If the cheaper supplier's field failure rate is more than 3.2 percentage points worse, it is the dearer option before inspection and rejects are even counted. In this example the 3-point gap almost cancels the saving on its own; inspection and rejects do the rest.
</div>

