<h2>Quality and Contract Mistakes in Custom DC Motor Sourcing</h2>

<h3>Mistake 2: Approving Samples Without Written Acceptance Criteria or a Golden Sample</h3>

<p>A sample that "works in the machine" is not an acceptance criterion. Before approving, write down each parameter with its nominal value, tolerance and test condition: no-load speed and current at rated voltage; speed, current and efficiency at the rated load point; temperature rise after a defined run; insulation resistance and hi-pot voltage; direction of rotation; critical dimensions; output backlash for geared motors; and noise, with measuring distance and background level stated. Then seal two or three approved units as <em>golden samples</em>, retained by both parties with their test data, so that a disputed batch is measured against the same physical reference. How undefined tests delay the development stage itself is covered in our article on <a href="/blog/custom-motor-manufacturing-delays-specifications/">custom motor manufacturing delays</a>.</p>

<h3>Mistake 3: Ignoring Production Consistency and Test Capability</h3>

<p>A sample is often built by the most experienced technician; series motors are built by the process. In a PMDC motor the magnet sets the motor constant, so magnet variation passes straight into performance:</p>

<div class="gsm-equation">\[ K_e = K_t \propto \Phi \quad \Rightarrow \quad \frac{\Delta N_0}{N_0} \approx -\frac{\Delta \Phi}{\Phi}, \qquad \frac{\Delta I_a}{I_a} \approx -\frac{\Delta \Phi}{\Phi} \]</div>

<p>A magnet lot 5 % weaker than the approved one gives roughly 5 % higher no-load speed, 5 % more current for the same torque and about 10 % more copper loss. Ask how the supplier controls this. At our Killa Pardi plant, PMDC motor testing includes magnet flux density and coercivity checks, ultrasonic flaw detection of shafts and laminations, computerised armature surge and HV dielectric tests across all commutator bars, dynamometer load testing, and endurance and temperature-rise testing for Class F (155 °C) insulation. The sequence is described on our <a href="/electromechanical-integrity/">electromechanical integrity</a> page and in <a href="/blog/electric-motor-testing-standards-before-a-unit-ships/">what happens before a motor ships</a>.</p>

<h3>Mistake 4: Accepting Silent Changes Without a Change-Notification Clause</h3>

<p>Many field problems trace back to an "equivalent" substitution nobody declared: a different magnet grade, enamelled wire, brush grade, bearing make, grease, gear material or sub-supplier, or a move to another production line. Put a product/process change notification (PCN) clause in the supply agreement listing what must be notified, how far in advance, and which re-qualification tests against the golden sample follow. A clear clause protects the supplier as well as the OEM.</p>

<h3>Mistake 5: Vague Warranty and Failure-Analysis Terms</h3>

<p>A one-line warranty clause leaves too many questions open. Agree when the period starts (dispatch, installation or the OEM's own sale), what counts as a failure, which conditions are excluded, such as overload, wrong supply voltage or water ingress beyond the IP rating, how failed motors are returned, who performs the failure analysis and how quickly, and what the report must contain. A root-cause report showing whether a failure was a brush, bearing, winding or application issue is worth more than a free replacement, because it tells you whether the next thousand motors will fail the same way.</p>

<h3>Mistake 6: Unclear Ownership of Drawings, Tooling and Design Data</h3>

<p>Agree in writing who owns the customer-specific drawing, any tooling the OEM has paid for, and the performance specification. The supplier's internal design data, such as winding details, normally remains theirs; what the OEM needs is an interface drawing and performance specification complete enough to qualify an alternative source if it ever must. Record where paid-for tooling is held and on what terms it is returned.</p>

<h3>Mistake 7: No Incoming Inspection Plan, or Too Much Faith in One</h3>

<p>Incoming inspection by attributes, usually with sampling plans taken from ISO 2859-1, checks a lot; it does not create quality. For a plan that inspects \( n \) motors and accepts the lot with up to \( c \) defectives, the probability of accepting a lot with defect fraction \( p \) is:</p>

<div class="gsm-equation">\[ P_a = \sum_{k=0}^{c} \binom{n}{k} p^k (1-p)^{n-k} \]</div>

<p>For an illustrative plan with \( n = 50 \) and \( c = 1 \):</p>

