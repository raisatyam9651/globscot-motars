<p>For an OEM, the purchase order for a custom motor is where the risk starts, not where it ends. The most expensive mistakes in <strong>custom DC motor sourcing</strong> seldom show up in the quotation comparison. They surface months later as line rejects, warranty claims, a magnet grade that quietly changed between batches, or a drawing the OEM discovers it does not own.</p>

<p>The decisions are the same whether you are buying a <a href="/products-pmdc-motors/">PMDC motor</a> for a mains-fed machine, a <a href="/products-pmdc-geared-motors/">PMDC geared motor</a> for a trolley, or a <a href="/products-bldc-motors/">BLDC motor</a> with its matched driver. This guide works through the mistakes procurement and engineering teams make most often, with a total-cost example in ₹, an incoming-inspection calculation and a supplier evaluation scorecard you can adapt.</p>

<div class="alert alert-info gsm-quick-summary" style="background-color: #f0f7fd; border-left: 4px solid #0056b3; padding: 15px; margin: 25px 0;">
<strong>Quick Summary:</strong> The costliest custom DC motor sourcing mistakes appear after the sample is approved. Avoid them by:
<ol>
<li>comparing suppliers on total cost of ownership, not unit price;</li>
<li>approving samples against written acceptance criteria and keeping a sealed golden sample;</li>
<li>verifying production consistency and in-house test capability;</li>
<li>agreeing change-notification, warranty, failure-analysis and drawing-ownership terms in writing;</li>
<li>planning incoming inspection, packaging, second sources and obsolescence before series supply begins.</li>
</ol>
</div>

<hr/>

<h2>Mistake 1: Buying on Unit Price Instead of Total Cost of Ownership</h2>

<p>A quotation comparison shows the one cost that is easiest to see. The costs that decide profitability arrive later: inspecting incoming motors, reworking machines that fail end-of-line test, and sending engineers to customer sites when a motor fails within warranty. Per motor, the cost to the OEM is better written as:</p>

<div class="gsm-equation">\[ C_{OEM} = P_{unit} + C_{insp} + p_{line}\,C_{line} + p_{field}\,C_{field} \]</div>

<p>where \( p_{line} \) and \( p_{field} \) are the fractions of motors rejected on the assembly line and failing in the field within warranty, and \( C_{line} \) and \( C_{field} \) are the cost of each event. Freight, inventory and engineering support can be added in the same way.</p>

<h4>Worked Example: Two Quotations for a 500 W PMDC Motor</h4>

<p>An OEM needs 1,000 custom 220 V DC, 500 W PMDC motors a year. Supplier A quotes ₹8,200 per motor and provides no test data, so every motor must be run-tested on arrival. Supplier B quotes ₹9,000 and ships dynamometer test records, so sampling is enough. A field failure costs the OEM about ₹25,000 (engineer visit, replacement motor, freight and downtime goodwill) and a line reject about ₹2,500. All figures are illustrative assumptions, not quotations; substitute your own.</p>

