<p>A weighted scorecard makes the comparison explicit and keeps unit price in proportion. Score each criterion from 1 to 5 against evidence, not claims, and combine the scores as:</p>

<div class="gsm-equation">\[ S = \sum_i w_i\, s_i \quad \text{with} \quad \sum_i w_i = 1 \]</div>

