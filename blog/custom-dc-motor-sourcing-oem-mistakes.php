<h2>Frequently Asked Questions (FAQ)</h2>

<h3>Q1. What is total cost of ownership for an OEM motor?</h3>
<p>Total cost of ownership is the full cost of a motor over the programme, not just its price. For the OEM it adds incoming inspection, assembly-line rejects and rework, warranty failures in the field, freight, inventory and engineering support to the unit price. For the machine owner it also includes energy, where a few points of efficiency on a motor running thousands of hours a year can outweigh a modest price difference within the first year or two.</p>

<h3>Q2. What is a golden sample in motor procurement?</h3>
<p>A golden sample is an approved motor, sealed and retained by both the OEM and the supplier together with its measured test data, that serves as the physical reference for series production. When a later batch is questioned, both sides test the disputed motors and the golden sample on the same set-up. It should be re-verified whenever a notified change is made to materials, components or the manufacturing process.</p>

<h3>Q3. How do I evaluate a custom DC motor manufacturer in India?</h3>
<p>Look beyond the quotation. Ask for the routine test list and sample test records, how magnets and armatures are checked, whether motors are dynamometer-tested, the quality system certificate, the change-notification procedure and an example failure-analysis report. Then weight these against total cost of ownership, delivery capability and track record in a scorecard. Globe Scott Motors, founded in 1985, operates an ISO 9001:2015 certified plant at Killa Pardi, Gujarat; see our <a href="/about-us/">company profile</a>.</p>

<h3>Q4. What is a PCN and why does it matter for motors?</h3>
<p>A product or process change notification (PCN) is a supplier's formal advance notice of any change that could affect form, fit, function or reliability, such as a new magnet grade, wire, brush grade, bearing make, lubricant, sub-supplier or production location. A PCN clause lets the OEM re-qualify the motor against the golden sample before changed parts reach its assembly line, instead of discovering the change through field failures.</p>

<h3>Q5. What AQL should I use for incoming inspection of motors?</h3>
<p>There is no universal figure; the plan should reflect how serious each defect is. Many OEMs apply a tighter AQL to critical characteristics such as insulation resistance, rotation direction and mounting dimensions, and a looser one to cosmetic defects, using sampling plans from ISO 2859-1. Remember that sampling only checks a lot: with 50 motors sampled and one defective allowed, a lot that is 4 % defective is still accepted about 40 % of the time.</p>

<h3>Q6. Should an OEM single-source a custom motor?</h3>
<p>Single-sourcing a custom motor is common and often sensible, because duplicating qualification and tooling is expensive. The risk lies in doing it without a plan. Keep safety stock sized to the supplier's replenishment time, hold an interface drawing and performance specification complete enough to qualify an alternative, understand the supplier's own long-lead parts, and agree advance notice of discontinuation so that a second source can be developed in time.</p>

