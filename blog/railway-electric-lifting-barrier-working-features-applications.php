<h2>1. Working Mechanics of Electric Lifting Barriers</h2>
<p>When an approaching train triggers track circuit sensors, the gate control unit signals the barrier motor drive:</p>

<ol>
<li><strong>Lowering Phase:</strong> The DC geared motor drives the barrier boom arm down from 90° vertical to 0° horizontal in 6 to 10 seconds while flashing warning lights and sounding alarms.</li>
<li><strong>Mechanical Locking & Detection:</strong> Once horizontal, internal limit switches cut motor current, and mechanical brakes hold the boom firm against wind uplift.</li>
<li><strong>Raising Phase:</strong> After the train clears the crossing, the motor reverses direction, raising the boom arm back to the vertical position.</li>
</ol>

