<h2>Frequently Asked Questions</h2>

<h3>Q1. What is a motor efficiency rating?</h3>
<p>It is mechanical power delivered at the shaft divided by electrical power drawn, as a percentage. The remainder becomes heat through copper losses, iron losses, friction and windage, and in brushed machines the brush friction and contact voltage drop.</p>

<h3>Q2. What IE class are DC motors?</h3>
<p>None. The IE1 to IE5 classes in IEC 60034-30-1 apply to line-operated AC induction motors. DC and electronically commutated motors fall outside that scope, so their efficiency must be compared at a stated operating point rather than by a class label.</p>

<h3>Q3. What efficiency should I expect from a PMDC motor?</h3>
<p>Typically 78 to 88 percent for a permanent magnet brushed DC motor, and 85 to 95 percent for a brushless DC motor. The gap comes mainly from brush friction and contact voltage drop, plus better heat removal from a stator-wound machine.</p>

<h3>Q4. How do I calculate the annual running cost of a motor?</h3>
<p>Divide the required shaft power in watts by the efficiency as a decimal, divide by 1000 to get kilowatts, then multiply by annual running hours and your energy tariff. For 750 W of shaft power at 80 percent efficiency over 7,200 hours at eight rupees per kilowatt hour, that is about 54,000 rupees a year.</p>

<h3>Q5. Is a more efficient motor always worth the extra cost?</h3>
<p>Only where running hours are high. Ten efficiency points on a sub-kilowatt drive is worth roughly 30,000 rupees over five years at three-shift operation, but only around 2,000 rupees at 500 hours a year. Below roughly 1,000 annual hours, upfront cost and reliability normally matter more.</p>

<h3>Q6. Why do two suppliers quote different efficiency for similar motors?</h3>
<p>Usually because the figures are at different operating points, or because one is a motor-only figure and the other includes the drive, or because one is calculated from design software and the other is measured on a dynamometer. Always ask which of the three you are being given.</p>

<h3>Q7. Does a gearbox affect the efficiency I actually get?</h3>
<p>Yes, and it multiplies. A motor at 90 percent driving a gearset at 80 percent delivers about 72 percent at the output shaft. Worm gearsets in particular can be substantially less efficient than helical or spur arrangements, so system efficiency should be calculated at the output.</p>

<h3>Q8. Does low efficiency affect motor life as well as energy cost?</h3>
<p>Yes. Losses appear as heat, and heat consumes the thermal budget set by the insulation class. On continuous duty a less efficient motor runs hotter for the same output, which shortens insulation life. Efficiency and longevity are effectively the same specification question on continuous duty.</p>

<hr/>

<h2>Conclusion</h2>
<p>An efficiency percentage is only meaningful with three things attached: the operating point it was measured at, whether it covers the drive, and how many hours a year the machine actually runs. With those, the number converts straight into a rupee figure that a finance team can act on.</p>
<p>For continuous duty the case usually makes itself. For intermittent duty it usually does not, and specifying for torque, reliability and upfront cost is the better decision.</p>

