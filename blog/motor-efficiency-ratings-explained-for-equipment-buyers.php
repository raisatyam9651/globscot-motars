<p>Efficiency is the easiest number on a motor datasheet to quote and the hardest to compare. If you have to justify a motor line item to a finance team, "this one is 90% efficient" is not an argument. A rupee figure per year is. This piece converts the vocabulary into that figure.</p>

<h2>What an Efficiency Rating Actually Measures</h2>

<p>Motor efficiency is simply mechanical power out divided by electrical power in, expressed as a percentage. Everything that does not come out of the shaft comes out as heat, and in a DC machine those losses fall into four buckets:</p>

<ul>
<li><strong>Copper losses (I&sup2;R).</strong> Resistive heating in the windings. These rise with the square of current, so they dominate at high load.</li>
<li><strong>Iron losses.</strong> Hysteresis and eddy currents in the laminations. Roughly proportional to speed and largely independent of load.</li>
<li><strong>Mechanical losses.</strong> Bearing friction and windage.</li>
<li><strong>Brush losses.</strong> Friction of the brushes on the commutator plus the voltage drop across the contact. This bucket exists only in brushed machines and is a large part of why brushless motors are more efficient.</li>
</ul>

<p>Typical bands: a permanent magnet brushed DC motor runs <strong>78&ndash;88%</strong>, a brushless DC motor <strong>85&ndash;95%</strong>. The construction reasons behind that gap are covered in <a href="/blog/pmdc-vs-bldc-motor-application-fit-guide/">our PMDC versus BLDC application fit guide</a>.</p>

<h2>A Clarification Worth Having Early: IE Classes and DC Motors</h2>

<p>Buyers often ask which IE class a DC motor is. The honest answer is that the question does not apply.</p>

<p>The IE efficiency classes IE1 through IE5, defined in IEC 60034-30-1, cover <strong>line-operated AC induction motors</strong>. They exist so that a buyer can compare two mains-fed AC motors on a common test basis. DC and electronically commutated motors are outside that scope: a DC motor's efficiency depends on the operating point set by the drive, so a single class label would not mean the same thing across two applications.</p>

<p>What this means practically is that DC motor efficiency must be compared <strong>at a stated operating point</strong> rather than by a class letter. That makes the next section unavoidable rather than optional.</p>

<h2>Worked Example: The Difference Over a Three-Shift Year</h2>

<p>Take a drive delivering <strong>750 W of shaft power</strong>, running three shifts. Assume 24 hours a day across 300 operating days, so <strong>7,200 running hours a year</strong>, at an industrial tariff of <strong>&#8377;8 per kWh</strong>.</p>

<table class="table table-bordered table-striped">
<thead>
<tr><th></th><th>Motor A at 80% efficiency</th><th>Motor B at 90% efficiency</th></tr>
</thead>
<tbody>
<tr><td>Shaft power required</td><td>750 W</td><td>750 W</td></tr>
<tr><td>Electrical input drawn</td><td>750 / 0.80 = 937.5 W</td><td>750 / 0.90 = 833.3 W</td></tr>
<tr><td>Annual energy</td><td>6,750 kWh</td><td>6,000 kWh</td></tr>
<tr><td>Annual energy cost</td><td>&#8377;54,000</td><td>&#8377;48,000</td></tr>
<tr><td><strong>Annual saving</strong></td><td colspan="2"><strong>&#8377;6,000</strong></td></tr>
<tr><td><strong>Over five years</strong></td><td colspan="2"><strong>&#8377;30,000</strong></td></tr>
</tbody>
</table>

<p>The arithmetic is worth keeping:</p>

<p><strong>Annual cost = (shaft watts &divide; efficiency) &divide; 1000 &times; running hours &times; tariff</strong></p>

<p>Two observations from the numbers. First, ten efficiency points on a sub-kilowatt motor is &#8377;30,000 over five years, which comfortably exceeds the price difference between most motor options at this size. Second, that conclusion depends entirely on the 7,200 hours. Run the same motor 500 hours a year and the five-year saving falls to roughly &#8377;2,000, which will not repay anything.</p>

<h2>Where Efficiency Matters Most, and Where It Does Not</h2>

<table class="table table-bordered table-striped">
<thead>
<tr><th>Duty Pattern</th><th>Indicative Annual Hours</th><th>Does Efficiency Drive the Decision?</th></tr>
</thead>
<tbody>
<tr><td>Continuous three-shift</td><td>6,000&ndash;8,000</td><td>Yes, decisively</td></tr>
<tr><td>Single shift</td><td>~2,000</td><td>Usually worth checking</td></tr>
<tr><td>Intermittent S3 duty</td><td>200&ndash;1,000</td><td>Rarely; upfront cost and reliability dominate</td></tr>
<tr><td>Occasional actuation</td><td>&lt; 200</td><td>No; specify for torque and life instead</td></tr>
</tbody>
</table>

<p>There is a second-order effect worth noting for continuous duty. Losses are heat, and heat consumes the thermal budget set by the insulation class. A less efficient motor runs hotter for the same output, which shortens insulation life as explained in <a href="/blog/motor-insulation-classes-explained-class-f-vs-class-h/">motor insulation classes explained</a>. On continuous duty, efficiency and longevity are the same conversation.</p>

<p>And on fan and pump loads specifically, absorbed power follows roughly the cube of speed, so the ability to run at reduced speed usually saves far more than a few points of motor efficiency ever will. That case is made in <a href="/blog/pmdc-motors-in-hvac-and-appliance-equipment/">where PMDC motors show up in HVAC and appliance equipment</a> and in <a href="/blog/pmdc-motors-for-pumps-benefits-applications-selection-guide/">PMDC motors for pumps</a>.</p>

<h2>Four Questions to Ask Before Comparing Two Efficiency Numbers</h2>

<ol>
<li><strong>At what operating point?</strong> Efficiency is a curve, not a constant. A motor peaks near its rated load and falls away sharply at light load. Two figures measured at different fractions of rated load are not comparable. Ask for efficiency at <em>your</em> duty point.</li>
<li><strong>Motor only, or motor plus drive?</strong> A brushless motor at 92% behind a controller at 95% is a system at about 87%. If one supplier quotes the motor and another quotes the system, the comparison is meaningless.</li>
<li><strong>Measured or calculated?</strong> Design software produces a number; a dynamometer produces a measurement. At Globe Scott Motors every motor is run on a dynamometer with horsepower and efficiency verified, using a back-to-back facility and an eddy-current dynamometer. The full sequence is on our <a href="/electromechanical-integrity/">electromechanical integrity page</a> and in <a href="/blog/electric-motor-testing-standards-before-a-unit-ships/">what happens to a motor before it ships</a>.</li>
<li><strong>Does a gearhead sit downstream?</strong> Gearbox efficiency multiplies. A 90% motor behind an 80% worm gearset delivers 72% at the output. Ratio and gearset efficiency are covered in <a href="/blog/custom-geared-pmdc-motors-gear-ratio-torque-selection/">selecting gear ratio and torque for custom geared PMDC motors</a>.</li>
</ol>

<h2>Turning This Into a Specification</h2>

<p>If efficiency genuinely matters for your machine, say so at enquiry stage and give the duty point rather than asking for a headline figure. Send annual running hours, load torque and speed, supply voltage and your energy tariff. A winding designed around your operating point will beat a catalogue motor chosen on its peak-efficiency claim.</p>

