<h2>1. How an Electric Point Machine Works</h2>

<ol>
<li><strong>Signal Command Initiation:</strong> The station interlocking controller sends a DC voltage pulse (110V DC) to the trackside point machine.</li>
<li><strong>Motor Activation & Unlocking:</strong> The internal DC electric motor rotates, driving a gear train that withdraws the mechanical locking mechanism securing the switch blades.</li>
<li><strong>Throwing Action:</strong> High continuous torque slides the switch point rails into the desired position (normal or reverse) across the stock rails within 3.5 seconds.</li>
<li><strong>Mechanical Locking & Detection:</strong> Once fully thrown, internal locking dogs drop into place, locking the switch. Electrical detection contacts close, signaling to the interlocking system that the track is safe for train passage.</li>
</ol>

<hr/>

<h2>2. Why Electric Point Machines Are Crucial for Railway Safety</h2>

<ul>
<li><strong>Derailment Prevention:</strong> Unless point blades are 100% locked against the stock rail, train wheel flanges could climb the rail. Point machines ensure zero rail gap.</li>
<li><strong>High-Speed Route Setting:</strong> Enables automated computer-controlled route setting across busy junctions without human delay.</li>
<li><strong>All-Weather Submersible Reliability:</strong> Trackside units must feature IP67 waterproof enclosures to operate reliably during monsoon submergence.</li>
<li><strong>Friction Clutch Protection:</strong> Internal friction clutches prevent motor damage if ballast stones jam the point blades.</li>
</ul>

