<h2>3. Frequently Asked Questions (FAQs)</h2>

<h3>Q1: What is the main purpose of an electric point machine in railway signalling?</h3>
<p>An electric point machine remotely unlocks, moves, and locks railway track switch points, allowing trains to change tracks safely without derailment risks.</p>

<h3>Q2: How does a point machine detect if a track point is properly locked?</h3>
<p>Internal mechanical detector slides physically check that the switch blade is tight against the stock rail before closing electrical detection contacts to clear the signal.</p>

<h3>Q3: What voltage powers electric point machines on Indian Railways?</h3>
<p>Indian Railways primarily uses 110V DC point machine motors, with 24V DC and 400V 3-phase AC options used for specialized lines.</p>

<h3>Q4: What happens if electrical power fails while a point machine is operating?</h3>
<p>Point machines include a manual crank handle socket so track maintainers can manually throw and lock the switch points using a mechanical key during power outages.</p>

<h3>Q5: Why is IP67 rating necessary for point machine motors?</h3>
<p>IP67 protection guarantees that water immersion during severe monsoon flooding does not short out motor windings or corrode internal gears.</p>

<h3>Q6: How fast does an electric point machine throw a railway switch?</h3>
<p>Standard electric point machines complete the unlocking, throwing, and locking operation within 2.5 to 4.0 seconds.</p>

<h3>Q7: What RDSO specifications apply to point machines in India?</h3>
<p>Point machines and their internal motors must comply with Indian Railways RDSO specifications IRS S-24 and IRS S-37.</p>

