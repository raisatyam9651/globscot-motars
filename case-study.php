<h2><strong>Indian Railways:</strong></h2>
<ul><li>More than 200,000 on the Indian Rail Tracks</li><li>400V AC successfully supplied more than 1000 motors</li><li>IP67 production and testing stage</li></ul>
<h2><strong>The Client</strong></h2>
<p><strong><em>For the last few years Globe Scott Motors has been successfully manufacturing and supplying Point Machine Motors to the Indian Railways, to help them manage the Railway line interruptions.</em></strong></p>
<p>GSM has continuously thrived to improvise and produce the highest quality motors, often jointly with RDSO team, to ensure that the operations are uninterrupted, considering the numbers of routes and people involved.</p>
<p>Water logging areas in rainy season – IP67, jointly with RDSO, and sent no. of motor to various railways for field trial and after a 2 and half year time, the results were satisfactory and we were awarded the approval to produce and manufacture the ip67 motor. For the first time India.</p>
<p>Railway wanted all the vendors to develop higher ac (400v) immunity level for certain section. With collaboration with RDSO, we achieved the ac immunity level up to 400v and the Indian Railway awarded us with the certification to produce the same. This motor used in specific region RESEARCH.</p>
<p>Our constant contribution towards the <strong>Indian Railways</strong> has helped achieve significant results in terms of 400VAC and IP67 watertight motors.</p>
<p>Plus, we were asked to extend out Railway product portfolio through the development of Point Machine, which is currently being tested at the Railways Testing center.</p>
