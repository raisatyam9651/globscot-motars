<h5><strong>Speed control over a wide range both above and below the rated speed:</strong></h5>
<p>The attractive feature of the dc motor is that it offers the wide range of speed control both above and below the rated speeds. This can be achieved in dc shunt motors by methods such as armature control method and field control method. This is one of the main applications in which dc motors are widely used in fine speed applications such as in rolling mills and in paper mills.</p>
<h5><strong>High starting torque:</strong></h5>
<p>DC series motors are termed as best suited drives for electrical traction applications used for driving heavy loads in starting conditions. DC series motors will have a staring torque as high as 500% compared to normal operating torque. Therefore dc series motors are used in the applications such as in electric trains and cranes.</p>
<h5><strong>Accurate steep less speed with constant torque:</strong></h5>
<p>Constant torque drives is one such the drives will have motor shaft torque constant over a given speed range. In such drives shaft power varies with speed.</p>
<ul><li>Quick starting, stopping, reversing and acceleration</li><li>Free from harmonics, reactive power consumption and many factors which makes dc motors more advantageous compared to ac induction motors.</li></ul>
